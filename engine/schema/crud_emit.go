// EmitGoWrapper writes the deterministic Go operation contract consumed by a
// profile wrapper. The emitted file contains ORM operation metadata only; a
// profile supplies entity-specific resolver and builder hooks.
func (m *CRUDManifest) EmitGoWrapper(w io.Writer, packageName string) error {
	var raw strings.Builder
	if err := m.emitGoWrapper(&raw, packageName); err != nil {
		return err
	}
	formatted, err := format.Source([]byte(raw.String()))
	if err != nil {
		return fmt.Errorf("format generated Go: %w", err)
	}
	_, err = w.Write(formatted)
	return err
}

func (m *CRUDManifest) emitGoWrapper(w io.Writer, packageName string) error {
	if !validPackageName(packageName) {
		return fmt.Errorf("invalid Go package name %q", packageName)
	}
	if _, err := fmt.Fprintf(w, "// Code generated by platformgen; DO NOT EDIT.\npackage %s\n\n", packageName); err != nil {
		return err
	}
	if _, err := io.WriteString(w, "// CRUD operations are executed by generated ORM builders. This file contains no SQL.\n\nimport (\n\t\"context\"\n\t\"fmt\"\n\n\t\"github.com/polyspec/orm/clients/go/orm\"\n)\n\n"); err != nil {
		return err
	}
	if _, err := io.WriteString(w, "type CRUDOperation struct { Route, Method, Path string; Scopes, Filters []CRUDBinding; Resource *CRUDBinding }\n"); err != nil {
		return err
	}
	if _, err := io.WriteString(w, "type CRUDBinding struct { Param, Field string; Order int }\n\n"); err != nil {
		return err
	}
	if _, err := io.WriteString(w, "type CRUDRunner interface { RunCRUD(context.Context, orm.Exec, CRUDOperation, any) (any, error) }\n\ntype CRUDClient struct { ctx context.Context; ex orm.Exec; runner CRUDRunner; callerOwned bool }\n\nfunc (c CRUDClient) Using(ctx context.Context, ex orm.Exec) CRUDClient { return CRUDClient{ctx: ctx, ex: ex, runner: c.runner} }\nfunc (c CRUDClient) UsingTx(ctx context.Context, tx orm.Exec) CRUDClient { return CRUDClient{ctx: ctx, ex: tx, runner: c.runner, callerOwned: true} }\nfunc (c CRUDClient) Execute(operation, route string, input any) (any, error) {\n\tif c.runner == nil { return nil, fmt.Errorf(\"crud runner is not configured\") }\n\tvar selected *CRUDOperation\n\tfor i := range CRUDOperations { if CRUDOperations[i].Route == route && CRUDOperations[i].Method == operation { selected = &CRUDOperations[i]; break } }\n\tif selected == nil { return nil, fmt.Errorf(\"unsupported CRUD operation %s %s\", operation, route) }\n\tif c.callerOwned { return c.runner.RunCRUD(c.ctx, c.ex, *selected, input) }\n\tvar result any\n\terr := orm.InTx(c.ctx, c.ex, func(tx orm.Exec) error { var err error; result, err = c.runner.RunCRUD(c.ctx, tx, *selected, input); return err })\n\treturn result, err\n}\n\n"); err != nil {
		return err
	}
	if _, err := io.WriteString(w, "var CRUDOperations = []CRUDOperation{\n"); err != nil {
		return err
	}
	for _, route := range m.Routes {
		for _, method := range route.Operations {
			fmt.Fprintf(w, "\t{Route:%q, Method:%q, Path:%q, Scopes:%s, Filters:%s, Resource:%s},\n", route.ID, method, route.Path, goBindings(route.Scopes), goBindings(route.Filters), goResource(route.Resource))
		}
	}
	_, err := io.WriteString(w, "}\n")
	return err
}

// EmitTypeScriptCRUD writes the CRUDUI route/form/list/action contract. It is
// valid TypeScript and uses only serialized metadata from the intermediate
// manifest.
func (m *CRUDManifest) EmitTypeScriptCRUD(w io.Writer) error {
	type spec struct {
		ID         string            `json:"id"`
		Path       string            `json:"path"`
		Scopes     []crudJSONBinding `json:"scopes"`
		Filters    []crudJSONBinding `json:"filters"`
		Resource   *crudJSONBinding  `json:"resource,omitempty"`
		Operations []string          `json:"operations"`
	}
	items := make([]spec, len(m.Routes))
	for i, route := range m.Routes {
		items[i] = spec{ID: route.ID, Path: route.Path, Scopes: convertBindings(route.Scopes), Filters: convertBindings(route.Filters), Resource: convertBinding(route.Resource), Operations: route.Operations}
	}
	b, err := json.MarshalIndent(items, "", "  ")
	if err != nil {
		return err
	}
	_, err = fmt.Fprintf(w, "// Code generated by platformgen; DO NOT EDIT.\nexport interface CrudBinding { readonly param: string; readonly field: string; readonly order?: number }\nexport interface CrudRoute { readonly id: string; readonly path: string; readonly scopes: readonly CrudBinding[]; readonly filters: readonly CrudBinding[]; readonly resource?: CrudBinding; readonly operations: readonly string[] }\nexport const crudRoutes: readonly CrudRoute[] = %s;\n", b)
	return err
}

// EmitPHPCRUD and EmitRustCRUD expose the same serialized intermediate
// contract to the other supported clients. They do not add language-specific
// CRUD semantics or database access.
func (m *CRUDManifest) EmitPHPCRUD(w io.Writer) error {
	b, err := m.MarshalIndent()
	if err != nil {
		return err
	}
	_, err = fmt.Fprintf(w, "<?php\n// Code generated by platformgen; DO NOT EDIT.\nconst CRUD_MANIFEST = %s;\n", b)
	return err
}

func (m *CRUDManifest) EmitRustCRUD(w io.Writer) error {
	b, err := m.MarshalIndent()
	if err != nil {
		return err
	}
	value := strings.ReplaceAll(string(b), `\`, `\\`)
	value = strings.ReplaceAll(value, `"`, `\"`)
	value = strings.ReplaceAll(value, "\n", `\n`)
	_, err = fmt.Fprintf(w, "// Code generated by platformgen; DO NOT EDIT.\npub const CRUD_MANIFEST_JSON: &str = \"%s\";\n", value)
	return err
}

type crudJSONBinding struct {
	Param string `json:"param"`
	Field string `json:"field"`
	Order int    `json:"order,omitempty"`
}

func convertBindings(in []CRUDBinding) []crudJSONBinding {
	out := make([]crudJSONBinding, len(in))
	for i, x := range in {
		out[i].Param, out[i].Field, out[i].Order = x.Param, x.Field, x.Order
	}
	return out
}

func convertBinding(in *CRUDBinding) *crudJSONBinding {
	if in == nil {
		return nil
	}
	out := convertBindings([]CRUDBinding{*in})
	return &out[0]
}

func goBindings(bindings []CRUDBinding) string {
	var b strings.Builder
	b.WriteString("[]CRUDBinding{")
	for _, x := range bindings {
		fmt.Fprintf(&b, "{Param:%q, Field:%q, Order:%d},", x.Param, x.Field, x.Order)
	}
	b.WriteByte('}')
	return b.String()
}
func goResource(binding *CRUDBinding) string {
	if binding == nil {
		return "nil"
	}
	return fmt.Sprintf("&CRUDBinding{Param:%q, Field:%q, Order:%d}", binding.Param, binding.Field, binding.Order)
}
func validPackageName(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if !(r == '_' || r >= 'a' && r <= 'z' || i > 0 && r >= '0' && r <= '9') {
			return false
		}
	}
	return true
}

// SortCRUDOperations is exposed for profile emitters that append their own
// operation hooks after the common manifest has been validated.
func (m *CRUDManifest) SortCRUDOperations() {
	sort.Slice(m.Routes, func(i, j int) bool { return m.Routes[i].ID < m.Routes[j].ID })
}
