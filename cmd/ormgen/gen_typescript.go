func writeTSPredicates(b *bytes.Buffer, ge goEntity, target string) {
	for _, p := range ge.Preds {
		args := make([]string, p.Arity)
		vals := make([]string, p.Arity)
		for i := range args {
			args[i] = fmt.Sprintf("value%d: unknown", i)
			vals[i] = fmt.Sprintf("value%d", i)
		}
		fmt.Fprintf(b, "  public %s(%s): this { %s.expression(%s,[%s]); return this; }\n", tsMethod(p.Name), strings.Join(args, ","), target, tsString(p.Expr), strings.Join(vals, ","))
	}
	for _, c := range ge.Cols {
		typ := tsPredicateType(c)
		for _, op := range c.Ops {
			method := tsMethod(c.Name) + op.Suffix
			switch op.Kind {
			case "one":
				fmt.Fprintf(b, "  public %s(value: %s): this { %s.predicate(%s,%s,value); return this; }\n", method, typ, target, tsString(c.Name), tsString(op.Op))
			case "list":
				fmt.Fprintf(b, "  public %s(values: readonly (%s)[]): this { %s.predicateList(%s,%s,values); return this; }\n", method, typ, target, tsString(c.Name), tsString(op.Op))
			case "pair":
				fmt.Fprintf(b, "  public %s(low: %s, high: %s): this { %s.predicateList(%s,%s,[low,high]); return this; }\n", method, typ, typ, target, tsString(c.Name), tsString(op.Op))
			case "none":
				fmt.Fprintf(b, "  public %s(): this { %s.predicateNull(%s,%s); return this; }\n", method, target, tsString(c.Name), tsString(op.Op))
			}
			if op.Op == "eq" {
				fmt.Fprintf(b, "  public %s(value: %s): this { return this.%s(value); }\n", tsMethod(c.Name), typ, method)
			}
		}
		for _, op := range c.ColOps {
			fmt.Fprintf(b, "  public %s(reference: ColumnReference): this { %s.predicateColumn(%s,%s,reference); return this; }\n", tsMethod(c.Name)+op.Suffix, target, tsString(c.Name), tsString(op.Op))
		}
	}
	for _, cols := range ge.Fulltext {
		fields := make([]string, len(cols))
		for i, c := range cols {
			fields[i] = tsString(c)
		}
		base := strings.Join(func() []string {
			x := make([]string, len(cols))
			for i, c := range cols {
				x[i] = pascal(c)
			}
			return x
		}(), "With")
		fmt.Fprintf(b, "  public %sMatch(value: string): this { %s.match([%s],value); return this; }\n", tsMethod(base), target, strings.Join(fields, ","))
		fmt.Fprintf(b, "  public %sMatchBoolean(value: string): this { %s.match([%s],value,true); return this; }\n", tsMethod(base), target, strings.Join(fields, ","))
	}
}
