func tsType(c *schema.Col) string {
	var t string
	if len(appStyles(c)) > 0 {
		t = "unknown"
	} else {
		switch c.Type {
		case "i32", "i64", "f64", "decimal":
			t = "number"
		case "bool":
			t = "boolean"
		case "date", "datetime":
			t = "string | Date"
		case "point":
			t = "Point"
		default:
			t = "string"
		}
	}
	if c.Nullable {
		t += " | null"
	}
	return t
}

func tsPredicateType(c goCol) string {
	if len(c.Styles) > 0 {
		return "unknown"
	}
	switch c.ColType {
	case "i32", "i64", "f64", "decimal":
		return "number"
	case "bool":
		return "boolean"
	case "date", "datetime":
		return "string | Date"
	case "point":
		return "Point"
	default:
		return "string"
	}
}

func tsString(s string) string {
	return "'" + strings.NewReplacer("\\", "\\\\", "'", "\\'", "\n", "\\n", "\r", "\\r").Replace(s) + "'"
}

func tsMethod(s string) string {
	p := pascal(s)
	if p == "" {
		return p
	}
	return strings.ToLower(p[:1]) + p[1:]
}

