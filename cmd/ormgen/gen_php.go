type phpCol struct {
	goCol
	PhpType string
	Agg     bool // countDistinct/min/max target (engine rule): styles empty or leading with ip, and not json/bytes
	IsPoint bool
}

type phpFinder struct {
	Method string
	Fields []phpCol
}

// phpPred is one manifest predicate: visible() / startedAfter($a0), body = expr(fragment, args).
type phpPred struct {
	Method, Expr, Params, Args string
}

type phpTmplData struct {
	Name, Type, Table, PK, PKPhp, Namespace, UpdatedTs, Scope, ScopeType string
	PKMethod                                                             string
	Auto                                                                 bool
	PKNames                                                              []string
	PKCols                                                               []goCol
	Cols                                                                 []phpCol
	EqCols                                                               []phpCol // columns that support the default equality predicate (getsBy/getCountBy)
	UniqueFinders                                                        []phpFinder
	Numeric                                                              []phpCol
	ParentCols                                                           []phpCol
	Rels                                                                 []goRel
	Links                                                                []goLink
	Indexes                                                              []string
	Fulltext                                                             [][]string
	Protected                                                            []string // PK and auto columns: never assigned by onDuplicateSetAll
	Predicates                                                           []phpPred
	AESCols                                                              []goCol
	AESVersion                                                           string
}

func genPHP(m *schema.Manifest, outDir, namespace string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	var boot bytes.Buffer
	boot.WriteString("<?php\n// Code generated by ormgen; DO NOT EDIT.\ndeclare(strict_types=1);\n\nnamespace " + namespace + ";\n\nuse Orm\\Registry;\n\n")
	boot.WriteString("require_once __DIR__ . '/Interfaces.php';\n\n")
	// The hash this code was generated from; Orm::init compares it once with schema.json and ormd.
	fmt.Fprintf(&boot, "Registry::generated('%s');\n", m.SchemaHash)
	for _, name := range m.Order {
		e := m.Entities[name]
		ge := buildGoEntity(m, e)
		d := phpTmplData{Name: ge.Name, Type: ge.Type, Table: ge.Table, PK: ge.PK, PKMethod: ge.PKMethod, PKNames: ge.PKNames, PKCols: ge.PKCols, Auto: ge.Auto, Namespace: namespace, Rels: ge.Rels, Links: ge.Links, Indexes: ge.Indexes, Fulltext: ge.Fulltext, UpdatedTs: ge.UpdatedTs, Scope: ge.Scope, AESCols: ge.AESCols, AESVersion: ge.AESVersion}
		if ge.Scope != "" {
			d.ScopeType = phpType(e.Column(ge.Scope))
		}
		for _, c := range ge.Cols {
			sc := e.Column(c.Name)
			pc := phpCol{goCol: c, PhpType: phpType(sc), Agg: (len(sc.Styles) == 0 || sc.Styles[0] == "ip") && sc.Type != "json" && sc.Type != "bytes", IsPoint: sc.Type == "point"}
			d.Cols = append(d.Cols, pc)
			if allowed(sc, "eq") {
				d.EqCols = append(d.EqCols, pc)
			}
			if c.Name == ge.PK {
				d.PKPhp = pc.PhpType
			}
			if c.PK || c.Auto || c.Managed {
				d.Protected = append(d.Protected, c.Name)
			}
		}
		phpByName := make(map[string]phpCol, len(d.Cols))
		for _, c := range d.Cols {
			phpByName[c.Name] = c
		}
		for _, f := range ge.UniqueFinders {
			pf := phpFinder{Method: f.Method, Fields: make([]phpCol, 0, len(f.Fields))}
			for _, c := range f.Fields {
				pf.Fields = append(pf.Fields, phpByName[c.Name])
			}
			d.UniqueFinders = append(d.UniqueFinders, pf)
		}
		for _, c := range ge.ParentCols {
			d.ParentCols = append(d.ParentCols, phpCol{goCol: c, PhpType: phpType(m.Entities[parentOf(m, e, c.Name)].Column(c.Name))})
		}
		for _, c := range ge.Numeric {
			d.Numeric = append(d.Numeric, phpCol{goCol: c, PhpType: phpType(e.Column(c.Name))})
		}
		predNames := make([]string, 0, len(e.Predicates))
		for n := range e.Predicates {
			predNames = append(predNames, n)
		}
		sort.Strings(predNames)
		for _, n := range predNames {
			pr := e.Predicates[n]
			params := make([]string, pr.Arity)
			args := make([]string, pr.Arity)
			for i := range params {
				params[i] = fmt.Sprintf("mixed $a%d", i)
				args[i] = fmt.Sprintf("$a%d", i)
			}
			d.Predicates = append(d.Predicates, phpPred{Method: camel(n), Expr: pr.Expr, Params: strings.Join(params, ", "), Args: strings.Join(args, ", ")})
		}
		var buf bytes.Buffer
		if err := phpTmpl.Execute(&buf, d); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		if err := os.WriteFile(filepath.Join(outDir, ge.Type+".php"), buf.Bytes(), 0o644); err != nil {
			return err
		}
		fmt.Fprintf(&boot, "Registry::register('%s', %sRow::class);\n", name, ge.Type)
	}
	return os.WriteFile(filepath.Join(outDir, "bootstrap.php"), boot.Bytes(), 0o644)
}
