test('the fixture policy declares sources that exist and agree with its lock, and the check passes on the fixture', (t) => {
  const root = mkdtempSync(path.join(tmpdir(), 'python-lock-fixture-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  cpSync(FIXTURE, root, { recursive: true });
  const entries = pythonLockEntries(root);
  assert.equal(entries.length, 1);
  assert.deepEqual(entries.map(entry => checkPythonLock({ root, entry })), [[]]);
});

test('the parsers read the forms of a requirement and of a constraint and refuse the rest', () => {
  assert.deepEqual(parseRequirements('requests[socks]>=2.30,<3 ; python_version >= "3.8"\n', 'r.txt'), [{ name: 'requests', url: null, specifiers: [{ op: '>=', version: '2.30' }, { op: '<', version: '3' }], line: 1, where: 'r.txt line 1' }]);
  assert.deepEqual(parseRequirements('# comment\n\nidna\n', 'r.txt').map(item => item.name), ['idna']);
  assert.throws(() => parseRequirements('idna===3.20\n', 'r.txt'), /r\.txt line 1: idna===3\.20 .* not read/);
  assert.throws(() => parseRequirements('idna==3.20.*\n', 'r.txt'), /r\.txt line 1: /);
  assert.deepEqual(parseConstraints(`kit-lib @ ${KIT_LIB}#sha256=${DIGEST}\nidna==3.20\n`, 'c.txt'), [
    { name: 'kit-lib', url: KIT_LIB, sha256: DIGEST, line: 1 },
    { name: 'idna', version: '3.20', line: 2 },
  ]);
  assert.throws(() => parseConstraints(`kit-lib @ ${KIT_LIB}\n`, 'c.txt'), /c\.txt line 1: kit-lib @ .* is not name==version or a direct reference with #sha256/);
});

test('the policy names each lock with its declared source, and a source is a requirements file or a pyproject.toml with an optional findLinks', () => {
  const schema = JSON.parse(readFileSync(new URL('../../scripts/kit/schema/dependency-policy.schema.json', import.meta.url), 'utf8'));
  const policy = locks => ({ schema: 1, composerPlatforms: [], pythonManifests: [], pythonLocks: locks, npmLocks: [], exceptions: [] });
  assert.deepEqual(validate(policy([ENTRY]), schema), []);
  assert.deepEqual(validate(policy([{ lock: 'packages/x-python/pylock.dev.toml', source: { requirements: 'requirements.in', constraints: 'constraints.txt' } }]), schema), []);
  assert.deepEqual(validate(policy([PYPROJECT_ENTRY]), schema), [], 'a pyproject.toml is a requirements source');
  assert.deepEqual(validate(policy([{ ...PYPROJECT_ENTRY, source: { ...PYPROJECT_ENTRY.source, findLinks: 'app/wheels' } }]), schema), [], 'findLinks is a directory relative to the root');
  assert.notDeepEqual(validate(policy([{ ...PYPROJECT_ENTRY, source: { ...PYPROJECT_ENTRY.source, findLinks: '/abs/links' } }]), schema), []);
  assert.notDeepEqual(validate(policy(['app/pylock.toml']), schema), [], 'a lock with no source is refused');
  assert.notDeepEqual(validate(policy([{ lock: 'app/pylock.toml' }]), schema), [], 'a lock with no source is refused');
  assert.notDeepEqual(validate(policy([{ lock: 'app/pylock.toml', source: { requirements: 'setup.cfg', constraints: 'c.txt' } }]), schema), [], 'a source is a requirements file of .txt or .in, or a pyproject.toml');
  assert.notDeepEqual(validate(policy([{ ...ENTRY, source: { ...ENTRY.source, extra: 'x' } }]), schema), []);
});
