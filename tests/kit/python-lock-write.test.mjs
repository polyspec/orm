// Tests of the writer of a Python lock (scripts/kit/python-lock.mjs, writePythonLock): it runs var/tools/bin/uv in a temporary
// directory with the basenames of the sources and the flags `pip compile <requirements> -c <constraints> --universal
// --generate-hashes --format pylock.toml -o pylock.toml`, checks the written lock against the sources, and renames it into
// place only when the check passes. The uv here is a stub that writes the lock text of STUB_LOCK, so no test reaches a network.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { writePythonLock } from '../../scripts/kit/python-lock.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');

const HEX = 'a'.repeat(64);
const ENTRY = { lock: 'app/pylock.toml', source: { requirements: 'app/requirements.txt', constraints: 'app/constraints.txt' } };
const EXPECTED_ARGS = ['pip', 'compile', 'requirements.txt', '-c', 'constraints.txt', '--universal', '--python-version', '3.14', '--generate-hashes', '--format', 'pylock.toml', '-o', 'pylock.toml'];

function lockText(packages) {
  const lines = ['# This file was autogenerated by uv via the following command:', '#    uv pip compile requirements.txt -c constraints.txt --universal --generate-hashes --format pylock.toml -o pylock.toml', 'lock-version = "1.0"', 'created-by = "uv"', 'requires-python = ">=3.14"', ''];
  for (const [name, version] of packages) {
    lines.push('[[packages]]', `name = "${name}"`, `version = "${version}"`, `wheels = [{ url = "https://files.pythonhosted.org/packages/x/${name}-${version}-py3-none-any.whl", hashes = { sha256 = "${HEX}" } }]`, '');
  }
  return lines.join('\n');
}

const GOOD = lockText([['requests', '2.34.2'], ['idna', '3.20']]);
const SOURCES = { 'app/requirements.txt': 'requests==2.34.2\n', 'app/constraints.txt': 'requests==2.34.2\nidna==3.20\n' };

// A checkout with the sources, the uv stub of var/tools/bin and the policy-free entry; the stub logs its arguments and working
// directory, writes STUB_LOCK to its -o file and exits with STUB_STATUS.
function checkout(t, { lock = GOOD, sources = SOURCES, existing = null, status = 0, extra = null, toolchain = { python: '3.14' } } = {}) {
  const root = realpathSync(mkdtempSync(path.join(tmpdir(), 'kit-python-lock-write-')));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  for (const [file, text] of Object.entries(sources)) {
    mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    writeFileSync(path.join(root, file), text);
  }
  if (existing !== null) writeFileSync(path.join(root, ENTRY.lock), existing);
  mkdirSync(path.join(root, 'config'), { recursive: true });
  writeFileSync(path.join(root, 'config/toolchain.json'), JSON.stringify(toolchain));
  // A consumer checkout may declare its scripts as ES modules; the stub runs the same in either case.
  writeFileSync(path.join(root, 'package.json'), JSON.stringify({ type: 'module', packageManager: 'npm@12.2.0' }));
  const text = lock.replaceAll('{{ROOT}}', root);
  mkdirSync(path.join(root, 'var/tools/bin'), { recursive: true });
  const log = path.join(root, 'uv.log');
  // The stub is a CommonJS file (.cjs) that the wrapper var/tools/bin/uv runs, so the type of a package.json does not change it.
  const script = path.join(root, 'var/tools/uv-stub.cjs');
  const stub = path.join(root, 'var/tools/bin/uv');
  writeFileSync(stub, `#!/bin/sh\nexec ${JSON.stringify(process.execPath)} ${JSON.stringify(script)} "$@"\n`);
  writeFileSync(script, `const fs = require('node:fs');
const args = process.argv.slice(2);
fs.appendFileSync(${JSON.stringify(log)}, JSON.stringify({ args, cwd: process.cwd(), listing: fs.readdirSync(process.cwd()).sort(), env: process.env.UV_CACHE_DIR ?? null }) + '\\n');
const out = args[args.indexOf('-o') + 1];
fs.writeFileSync(out, ${JSON.stringify(text)});
${extra ? `fs.writeFileSync(${JSON.stringify(extra)}, 'stray');` : ''}
process.exit(${status});
`);
  chmodSync(stub, 0o755);
  return { root, log: () => (existsSync(log) ? readFileSync(log, 'utf8').trim().split('\n').map(line => JSON.parse(line)) : []) };
}

const temporary = root => readdirSync(path.join(root, 'var/tools')).filter(name => name.startsWith('python-lock-'));

test('the writer runs uv with the sources by their names, the pinned flags and a temporary directory, and renames the checked lock into place', (t) => {
  const { root, log } = checkout(t);
  const written = writePythonLock({ root, entry: ENTRY, env: process.env });
  assert.deepEqual(written, { file: ENTRY.lock });
  assert.equal(readFileSync(path.join(root, ENTRY.lock), 'utf8'), GOOD);
  const [call] = log();
  assert.deepEqual(call.args, EXPECTED_ARGS);
  assert.notEqual(call.cwd, root, 'uv runs in a temporary directory, so the header of the lock names only the source names');
  assert.deepEqual(temporary(root), [], 'the temporary directory is removed');
  assert.deepEqual(readdirSync(path.join(root, 'app')).sort(), ['constraints.txt', 'pylock.toml', 'requirements.txt'], 'no stray file is written beside the sources');
});

test('a transitive package that the constraints leave unpinned is refused by the writer, which names the package and keeps the lock it had', (t) => {
  const unpinned = lockText([['requests', '2.34.2'], ['idna', '3.20'], ['colorama', '0.4.6']]);
  const previous = 'previous lock\n';
  const { root } = checkout(t, { lock: unpinned, existing: previous });
  assert.throws(() => writePythonLock({ root, entry: ENTRY, env: process.env }), /^Error: app\/pylock\.toml: colorama 0\.4\.6 is in the lock and has no pin in app\/constraints\.txt\./);
  assert.equal(readFileSync(path.join(root, ENTRY.lock), 'utf8'), previous, 'the lock is not replaced');
  assert.deepEqual(temporary(root), [], 'the temporary directory is removed');
});

test('a failing uv writes no lock, names its exit status, and removes its temporary directory', (t) => {
  const { root } = checkout(t, { status: 2 });
  assert.throws(() => writePythonLock({ root, entry: ENTRY, env: process.env }), /uv pip compile requirements\.txt -c constraints\.txt .* ended with exit status 2/);
  assert.equal(existsSync(path.join(root, ENTRY.lock)), false);
  assert.deepEqual(temporary(root), []);
});

test('the writer refuses a source that is not written in the declared form before it runs uv', (t) => {
  const { root, log } = checkout(t, { sources: { 'app/requirements.txt': 'requests>=2\n', 'app/constraints.txt': 'requests>=2\nidna==3.20\n' } });
  assert.throws(() => writePythonLock({ root, entry: ENTRY, env: process.env }), /app\/constraints\.txt line 1: requests>=2 is not name==version/);
  assert.deepEqual(log(), []);
});

test('the writer refuses a missing uv and names the install of var/tools/bin/uv', (t) => {
  const { root } = checkout(t);
  rmSync(path.join(root, 'var/tools/bin/uv'));
  assert.throws(() => writePythonLock({ root, entry: ENTRY, env: process.env }), /var\/tools\/bin\/uv is missing; run make install-tools TOOLS=uv/);
});

test('the writer refuses a lock that holds a package at another version than its pin, and writes nothing', (t) => {
  const drifted = lockText([['requests', '2.34.3'], ['idna', '3.20']]);
  const { root } = checkout(t, { lock: drifted });
  assert.throws(() => writePythonLock({ root, entry: ENTRY, env: process.env }), /app\/pylock\.toml: requests 2\.34\.3 is locked, app\/constraints\.txt pins requests 2\.34\.2/);
  assert.equal(existsSync(path.join(root, ENTRY.lock)), false);
});

test('a stray file that uv writes beside its output is not kept', (t) => {
  const { root } = checkout(t, { extra: 'stray.txt' });
  writePythonLock({ root, entry: ENTRY, env: process.env });
  assert.deepEqual(readdirSync(path.join(root, 'app')).sort(), ['constraints.txt', 'pylock.toml', 'requirements.txt']);
  assert.deepEqual(temporary(root), []);
});

const PYPROJECT = '[project]\nname = "app"\nversion = "0.0.0"\ndependencies = [\n  "requests==2.34.2",\n  "idna>=3.0",\n]\n';
const PYPROJECT_ENTRY = { lock: 'app/pylock.toml', source: { requirements: 'app/pyproject.toml', constraints: 'app/constraints.txt' } };
const PYPROJECT_SOURCES = { 'app/pyproject.toml': PYPROJECT, 'app/constraints.txt': SOURCES['app/constraints.txt'] };

test('a requirements source that is a pyproject.toml is copied into the temporary directory under its name, and uv reads it there', (t) => {
  const { root, log } = checkout(t, { sources: PYPROJECT_SOURCES });
  assert.deepEqual(writePythonLock({ root, entry: PYPROJECT_ENTRY, env: process.env }), { file: ENTRY.lock });
  const [call] = log();
  assert.deepEqual(call.args, ['pip', 'compile', 'pyproject.toml', '-c', 'constraints.txt', '--universal', '--python-version', '3.14', '--generate-hashes', '--format', 'pylock.toml', '-o', 'pylock.toml']);
  assert.deepEqual(call.listing, ['constraints.txt', 'pyproject.toml']);
});

test('a pyproject.toml that lists dependencies in [project].dynamic is refused before uv runs', (t) => {
  const dynamic = PYPROJECT.replace('version = "0.0.0"\n', 'version = "0.0.0"\ndynamic = ["dependencies"]\n');
  const { root, log } = checkout(t, { sources: { ...PYPROJECT_SOURCES, 'app/pyproject.toml': dynamic } });
  assert.throws(() => writePythonLock({ root, entry: PYPROJECT_ENTRY, env: process.env }), /app\/pyproject\.toml: \[project\]\.dynamic lists dependencies/);
  assert.deepEqual(log(), []);
});

test('findLinks makes uv offline and the lock keeps no machine path: a file URL is written as a path relative to the lock', (t) => {
  const wheel = Buffer.from('requests wheel');
  const sha = createHash('sha256').update(wheel).digest('hex');
  const lock = `lock-version = "1.0"\ncreated-by = "uv"\nrequires-python = ">=3.14"\n\n[[packages]]\nname = "requests"\nversion = "2.34.2"\nwheels = [{ url = "file://{{ROOT}}/app/links/requests-2.34.2-py3-none-any.whl", hashes = { sha256 = "${sha}" } }]\n`;
  const entry = { lock: 'app/pylock.toml', source: { requirements: 'app/requirements.txt', constraints: 'app/constraints.txt', findLinks: 'app/links' } };
  const sources = { 'app/requirements.txt': 'requests==2.34.2\n', 'app/constraints.txt': 'requests==2.34.2\n', 'app/links/requests-2.34.2-py3-none-any.whl': wheel };
  const { root, log } = checkout(t, { lock, sources });
  writePythonLock({ root, entry, env: process.env });
  const [call] = log();
  assert.deepEqual(call.args, [...EXPECTED_ARGS, '--no-index', '--find-links', path.join(root, 'app/links')]);
  const written = readFileSync(path.join(root, ENTRY.lock), 'utf8');
  assert.ok(written.includes('path = "links/requests-2.34.2-py3-none-any.whl"'), written);
  assert.ok(!written.includes('file:'), 'no file URL is kept');
  assert.ok(!written.includes(root), 'no checkout path is kept');
});

test('the lower bound of the resolution is the declared python minor, and a toolchain without one is refused before uv runs', (t) => {
  const { root, log } = checkout(t, { toolchain: {} });
  assert.throws(() => writePythonLock({ root, entry: ENTRY, env: process.env }), /declares no python minor, the lower bound of the resolution/);
  assert.deepEqual(log(), []);
});

test('findLinks outside the package of the lock is refused before uv runs', (t) => {
  const entry = { lock: 'app/pylock.toml', source: { requirements: 'app/requirements.txt', constraints: 'app/constraints.txt', findLinks: 'links' } };
  const { root, log } = checkout(t);
  assert.throws(() => writePythonLock({ root, entry, env: process.env }), /app\/pylock\.toml: findLinks links is outside app, the package of app\/pylock\.toml/);
  assert.deepEqual(log(), []);
});

test('findLinks outside the checkout is refused before uv runs', (t) => {
  const entry = { lock: 'app/pylock.toml', source: { requirements: 'app/requirements.txt', constraints: 'app/constraints.txt', findLinks: '../elsewhere' } };
  const { root, log } = checkout(t);
  assert.throws(() => writePythonLock({ root, entry, env: process.env }), /app\/pylock\.toml: findLinks \.\.\/elsewhere is outside the checkout/);
  assert.deepEqual(log(), []);
});
