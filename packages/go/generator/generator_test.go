// Requirements: DBS-104, SCH-2.
func TestGenerateUsesCanonicalManifestForGoClient(t *testing.T) {
	testcase.Start(t, testcase.Compute)
	manifest := sampleModel(t)
	out := filepath.Join(t.TempDir(), "model")
	if err := Generate(Options{Model: manifest, OutputDir: out}); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(out, "sample.go")); err != nil {
		t.Fatalf("generated ORM client is missing: %v", err)
	}
	orm, err := os.ReadFile(filepath.Join(out, "orm.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"const ManifestHash = " + strconv.Quote(manifest.ManifestHash),
		"const ManifestText = " + goStringLiteral(manifest.ManifestText),
		"var Schema = &orm.Schema{Hash: ManifestHash, Text: ManifestText}",
	} {
		if !strings.Contains(string(orm), want) {
			t.Errorf("orm.go does not carry generated manifest value %q", want)
		}
	}
}

func TestGenerateUsesRequestedGoPackageName(t *testing.T) {
	testcase.Start(t, testcase.Compute)
	manifest := sampleModel(t)
	out := t.TempDir()
	if err := Generate(Options{Model: manifest, OutputDir: out, PackageName: "storage"}); err != nil {
		t.Fatal(err)
	}
	body, err := os.ReadFile(filepath.Join(out, "sample.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(body), "// Code generated by orm-gen; DO NOT EDIT.\n\npackage storage\n") {
		t.Fatalf("generated client does not use requested package: %s", body[:min(len(body), 120)])
	}
	init, err := os.ReadFile(filepath.Join(out, "orm.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(init), "package storage") {
		t.Fatal("generated initializer does not use requested package")
	}
}

// sampleModel is the runtime model of a table with one identity column.
func sampleModel(t *testing.T) *runtimemodel.Model {
	t.Helper()
	m, diagnostics := runtimemodel.LoadDocuments([]string{"dbspec 1 sample\n\ntable sample {\n  seq i64 identity\n  primary key (seq)\n}\n"})
	if len(diagnostics) > 0 {
		t.Fatal(runtimemodel.DiagnosticsError(diagnostics))
	}
	return m
}

// repositoryRoot discovers the checkout containing this test from its working directory, as go test runs tests in
// their package directory. It accepts a parent only when both the tracked workspace marker and the declared fixture
// are present; it never uses the compiled test binary's source path.
func repositoryRoot(t *testing.T) string {
	t.Helper()
	directory, err := os.Getwd()
	if err != nil {
		t.Fatalf("read the generator test working directory: %v", err)
	}
	for {
		_, workspaceErr := os.Stat(filepath.Join(directory, "go.work"))
		_, fixtureErr := os.Stat(filepath.Join(directory, "contracts", "fixtures", "bench", "dbspec-set.json"))
		if workspaceErr == nil && fixtureErr == nil {
			return directory
		}
		parent := filepath.Dir(directory)
		if parent == directory {
			t.Fatal("cannot find repository root containing go.work and contracts/fixtures/bench/dbspec-set.json")
		}
		directory = parent
	}
}

// TestGenerateExternalTables checks that a set using external documents (external) generates the
// models of the tables it owns and the read-only models of the tables it uses from external documents,
// and none of an unused external table, and that the text of the used tables is carried in the schema value.
// Requirements: DBS-110.
func TestGenerateExternalTables(t *testing.T) {
	testcase.Start(t, testcase.Compute)
	fixtures := filepath.Join("..", "..", "..", "contracts", "fixtures", "external")
	text := func(name string) string {
		b, err := os.ReadFile(filepath.Join(fixtures, name))
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	m, diagnostics := runtimemodel.LoadDocumentSet([]string{text("member.dbs")}, []string{text("core.dbs")})
	if len(diagnostics) > 0 {
		t.Fatal(runtimemodel.DiagnosticsError(diagnostics))
	}
	out := filepath.Join(t.TempDir(), "member")
	if err := Generate(Options{Model: m, OutputDir: out}); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(out)
	if err != nil {
		t.Fatal(err)
	}
	var files []string
	for _, e := range entries {
		files = append(files, e.Name())
	}
	if strings.Join(files, " ") != "ext_account.go ext_audit.go ext_post.go ext_post_history.go orm.go" {
		t.Fatalf("generated files %v, want the used external tables ext_account and ext_audit, the owned tables ext_post and ext_post_history and orm.go", files)
	}
	body, err := os.ReadFile(filepath.Join(out, "orm.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(body), "External: ExternalText}") || !strings.Contains(string(body), `const ExternalText = "dbspec 1 ext_core\n"`) {
		t.Fatalf("orm.go does not carry the external text:\n%s", body)
	}
	if strings.Contains(string(body), "ext_session") {
		t.Fatal("orm.go carries ext_session, which the set does not use")
	}
}

// TestGenerateBenchDocumentSet checks that the declared bench set loads both owned documents and its external document,
// and generates a model for every table in that set.
// Requirements: SCH-1.
func TestGenerateBenchDocumentSet(t *testing.T) {
	testcase.Start(t, testcase.Compute)
	setPath := filepath.Join(repositoryRoot(t), "contracts", "fixtures", "bench", "dbspec-set.json")
	manifest, err := runtimemodel.LoadSetFile(setPath)
	if err != nil {
		t.Fatal(err)
	}
	sharedNote := manifest.Entities["shared_note"]
	if sharedNote == nil || !sharedNote.External {
		t.Fatal("bench_shared.dbs shared_note is not loaded as an external entity")
	}
	want := []string{"account", "account_project", "audit_record", "audited_note", "audited_note_history", "author", "bind_cell", "clock_cell", "composite_account", "composite_membership", "day_cell", "hex_cell", "note_reader", "project", "service", "service_member", "service_region", "shared_note", "soft_link", "soft_record", "task", "time_cell", "upsert_cell", "user", "uuid_cell"}
	got := make([]string, 0, len(manifest.Entities))
	for name := range manifest.Entities {
		got = append(got, name)
	}
	sort.Strings(got)
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("bench set entities = %v, want %v", got, want)
	}
	out := filepath.Join(t.TempDir(), "model")
	if err := Generate(Options{Model: manifest, OutputDir: out}); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(out)
	if err != nil {
		t.Fatal(err)
	}
	wantFiles := make([]string, 0, len(want)+1)
	for _, entity := range want {
		wantFiles = append(wantFiles, entity+".go")
	}
	wantFiles = append(wantFiles, "orm.go")
	sort.Strings(wantFiles)
	gotFiles := make([]string, len(entries))
	for i, entry := range entries {
		gotFiles[i] = entry.Name()
	}
	if !reflect.DeepEqual(gotFiles, wantFiles) {
		t.Fatalf("generated bench set files = %v, want %v", gotFiles, wantFiles)
	}
}
