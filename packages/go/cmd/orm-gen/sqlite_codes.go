// orm-gen sqlite-codes: the sqlite_result_codes table of docs/spec/sqlite-result-codes.yaml → one lookup per language, which ends a
// SQLite driver error message with the name of its extended result code (INT-154). SQLite has no API that names a code.
//
//	orm-gen sqlite-codes --lang go --out packages/go/orm/sqlite/result_codes.go
//	orm-gen sqlite-codes --lang php --out packages/php/src/SqliteCodes.php
//	orm-gen sqlite-codes --lang php-extension --out packages/php-ext/src/sqlite_codes.h
//	orm-gen sqlite-codes --lang rust --out packages/rust/orm/src/sqlite_codes.rs
//	orm-gen sqlite-codes --lang typescript --out packages/ts/src/sqlite-codes.ts
//	orm-gen sqlite-codes --lang python --out packages/python/src/polyspec/orm/_sqlite_codes.py
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"github.com/polyspec/orm/packages/go/internal/message"
)

type sqliteCode struct {
	Name  string
	Value int
}

// readSQLiteCodes reads the "- name: X" lines of the sqlite_result_codes list, each followed by "value: N".
func readSQLiteCodes(path string) ([]sqliteCode, error) {
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var out []sqliteCode
	seen := map[int]string{}
	listed := false
	for _, line := range strings.Split(string(src), "\n") {
		t := strings.TrimSpace(line)
		switch {
		case line == "sqlite_result_codes:":
			listed = true
		case !listed:
		case strings.HasPrefix(t, "- name:"):
			out = append(out, sqliteCode{Name: strings.TrimSpace(strings.TrimPrefix(t, "- name:")), Value: -1})
		case strings.HasPrefix(t, "value:") && len(out) > 0:
			last := &out[len(out)-1]
			value, err := strconv.Atoi(strings.TrimSpace(strings.TrimPrefix(t, "value:")))
			if err != nil || value < 0 {
				return nil, fmt.Errorf("%s: %s has no non-negative integer value", path, last.Name)
			}
			if other, ok := seen[value]; ok {
				return nil, fmt.Errorf("%s: %s and %s have the same value %d", path, other, last.Name, value)
			}
			seen[value], last.Value = last.Name, value
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no sqlite_result_codes found", path)
	}
	for _, c := range out {
		if c.Value < 0 {
			return nil, fmt.Errorf("%s: %s has no value", path, c.Name)
		}
	}
	return out, nil
}

func sqliteCodesCmd(args []string) {
	fs := flag.NewFlagSet("sqlite-codes", flag.ExitOnError)
	lang := fs.String("lang", "", "go|php|php-extension|rust|typescript|python (required)")
	out := fs.String("out", "", "output file (required)")
	yaml := fs.String("yaml", "docs/spec/sqlite-result-codes.yaml", "SQLite result code table")
	if err := fs.Parse(args); err != nil {
		usage()
	}
	if *lang == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "usage: orm-gen sqlite-codes --lang go|php|php-extension|rust|typescript|python --out <file> [--yaml docs/spec/sqlite-result-codes.yaml]")
		os.Exit(2)
	}
	codes, err := readSQLiteCodes(*yaml)
	if err != nil {
		fail(err)
	}
	body, err := sqliteCodesSource(*lang, codes)
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, body, 0o644); err != nil {
		fail(err)
	}
	fmt.Fprintf(os.Stderr, "orm-gen: %d SQLite result codes → %s\n", len(codes), *out)
}

const sqliteCodesHeader = "Code generated by orm-gen sqlite-codes from docs/spec/sqlite-result-codes.yaml; DO NOT EDIT."

// sqliteCodesSource is the lookup of one language: the suffix of a SQLite error message with result code n is " (NAME)",
// or " (SQLite result code n)" for a code the table does not list.
func sqliteCodesSource(lang string, codes []sqliteCode) ([]byte, error) {
	var sb strings.Builder
	switch lang {
	case "go":
		sb.WriteString("// " + sqliteCodesHeader + "\n\npackage sqlite\n\nimport \"strconv\"\n\n// resultCodeNames names the SQLite result codes, primary and extended (docs/spec/sqlite-result-codes.yaml).\nvar resultCodeNames = map[int]string{\n")
		for _, c := range codes {
			fmt.Fprintf(&sb, "\t%d: %q,\n", c.Value, c.Name)
		}
		sb.WriteString("}\n\n// resultCodeSuffix ends the message of a SQLite error with its result code: the name in parentheses, or the number of\n// a code the table does not list (INT-154).\nfunc resultCodeSuffix(code int) string {\n\tif name, ok := resultCodeNames[code]; ok {\n\t\treturn \" (\" + name + \")\"\n\t}\n\treturn \" (SQLite result code \" + strconv.Itoa(code) + \")\"\n}\n")
		return format.Source([]byte(sb.String()))
	case "rust":
		sb.WriteString("//! " + sqliteCodesHeader + "\n//! The SQLite result codes, primary and extended (docs/spec/sqlite-result-codes.yaml).\n\n/// Ends the message of a SQLite error with its result code: the name in parentheses, or the number of a code the table\n/// does not list (INT-154).\npub(crate) fn result_code_suffix(code: i64) -> String {\n    let name = match code {\n")
		for _, c := range codes {
			fmt.Fprintf(&sb, "        %d => %q,\n", c.Value, c.Name)
		}
		sb.WriteString("        _ => return format!(\" (SQLite result code {code})\"),\n    };\n    format!(\" ({name})\")\n}\n")
	case "typescript":
		sb.WriteString("// " + sqliteCodesHeader + "\n// The SQLite result codes, primary and extended (docs/spec/sqlite-result-codes.yaml).\n\nconst NAMES: ReadonlyMap<number, string> = new Map([\n")
		for _, c := range codes {
			fmt.Fprintf(&sb, "  [%d, '%s'],\n", c.Value, c.Name)
		}
		sb.WriteString("]);\n\n/** Ends the message of a SQLite error with its result code: the name in parentheses, or the number of a code the table does not list (INT-154). */\nexport function sqliteResultCodeSuffix(code: number): string {\n  const name = NAMES.get(code);\n  return name === undefined ? ` (SQLite result code ${code})` : ` (${name})`;\n}\n")
	case "python":
		sb.WriteString("# " + sqliteCodesHeader + "\n# The SQLite result codes, primary and extended (docs/spec/sqlite-result-codes.yaml).\n\n_NAMES = {\n")
		for _, c := range codes {
			fmt.Fprintf(&sb, "    %d: \"%s\",\n", c.Value, c.Name)
		}
		sb.WriteString("}\n\n\ndef result_code_suffix(code: int) -> str:\n    \"\"\"Ends the message of a SQLite error with its result code: the name in parentheses, or the number of a code the\n    table does not list (INT-154).\"\"\"\n    name = _NAMES.get(code)\n    return f\" (SQLite result code {code})\" if name is None else f\" ({name})\"\n")
	case "php":
		sb.WriteString("<?php\n\n// " + sqliteCodesHeader + "\ndeclare(strict_types=1);\n\nnamespace Polyspec\\Orm;\n\n/**\n * @internal The SQLite result codes, primary and extended (docs/spec/sqlite-result-codes.yaml).\n */\nfinal class SqliteCodes\n{\n    private const NAMES = [\n")
		for _, c := range codes {
			fmt.Fprintf(&sb, "        %d => '%s',\n", c.Value, c.Name)
		}
		sb.WriteString("    ];\n\n    /**\n     * Ends the message of a SQLite error with its result code: the name in parentheses, or the number of a code the\n     * table does not list (INT-154).\n     */\n    public static function suffix(int $code): string\n    {\n        $name = self::NAMES[$code] ?? null;\n        return $name === null ? \" (SQLite result code $code)\" : \" ($name)\";\n    }\n}\n")
	case "php-extension":
		sb.WriteString("/* " + sqliteCodesHeader + "\n * The SQLite result codes, primary and extended (docs/spec/sqlite-result-codes.yaml). */\n#ifndef POLYSPEC_ORM_SQLITE_CODES_H\n#define POLYSPEC_ORM_SQLITE_CODES_H\n\n/* The name of a SQLite result code, or NULL for a code the table does not list (INT-154). */\nstatic const char *sqlite_result_code_name(zend_long code)\n{\n    switch (code) {\n")
		for _, c := range codes {
			fmt.Fprintf(&sb, "    case %d: return \"%s\";\n", c.Value, c.Name)
		}
		sb.WriteString("    default: return NULL;\n    }\n}\n\n#endif\n")
	default:
		return nil, message.Errorf("unknown lang %q", lang)
	}
	return []byte(sb.String()), nil
}
