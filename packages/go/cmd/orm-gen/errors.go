// orm-gen errors: docs/spec/errors.yaml → one constants file per language, so every client names the
// same codes (docs/plans/execution/checklist.md T5.2). The yaml is a flat list; no YAML library is needed.
//
//	orm-gen errors --lang go --out packages/go/orm/codes.go
//	orm-gen errors --lang php --out packages/php/src/Code.php
//	orm-gen errors --lang php-extension --out packages/php-ext/src/polyspec_orm.stub.php
//	orm-gen errors --lang rust --out packages/rust/orm/src/codes.rs
//	orm-gen errors --lang typescript --out packages/ts/src/codes.ts
//	orm-gen errors --lang python --out packages/python/src/polyspec/orm/codes.py
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

type errCode struct{ Code, Origin, Comment string }

func readErrorCodes(path string) ([]errCode, error) {
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var out []errCode
	for _, line := range strings.Split(string(src), "\n") {
		t := strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(t, "- code:"):
			rest := strings.TrimSpace(strings.TrimPrefix(t, "- code:"))
			code, comment, _ := strings.Cut(rest, "#")
			out = append(out, errCode{Code: strings.TrimSpace(code), Comment: strings.TrimSpace(comment)})
		case strings.HasPrefix(t, "origin:") && len(out) > 0:
			out[len(out)-1].Origin = strings.TrimSpace(strings.TrimPrefix(t, "origin:"))
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no codes found", path)
	}
	return out, nil
}

func errorsCmd(args []string) {
	fs := flag.NewFlagSet("errors", flag.ExitOnError)
	lang := fs.String("lang", "", "go|php|php-extension|rust|typescript|python (required)")
	out := fs.String("out", "", "output file (required)")
	yaml := fs.String("yaml", "docs/spec/errors.yaml", "error catalog")
	// With ExitOnError, Parse ends the process on a bad flag itself; an error it returns is the same usage error.
	if err := fs.Parse(args); err != nil {
		usage()
	}
	if *lang == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "usage: orm-gen errors --lang go|php|php-extension|rust|typescript|python --out <file> [--yaml docs/spec/errors.yaml]")
		os.Exit(2)
	}
	codes, err := readErrorCodes(*yaml)
	if err != nil {
		fail(err)
	}
	var sb strings.Builder
	switch *lang {
	case "go":
		sb.WriteString("// Code generated by orm-gen errors from docs/spec/errors.yaml; DO NOT EDIT.\n\npackage orm\n\n// Error codes shared by the engine and every executor (docs/spec/errors.yaml).\nconst (\n")
		for _, c := range codes {
			detail := strings.TrimSpace(c.Comment)
			note := c.Origin
			if detail != "" {
				note += ": " + detail
			}
			fmt.Fprintf(&sb, "\tCode%s = %q // %s\n", constantName(c.Code), c.Code, note)
		}
		sb.WriteString(")\n")
	case "php":
		sb.WriteString("<?php\n// Code generated by orm-gen errors from docs/spec/errors.yaml; DO NOT EDIT.\ndeclare(strict_types=1);\n\nnamespace Polyspec\\Orm;\n\n/** Error codes shared by the engine and every executor (docs/spec/errors.yaml). */\nfinal class Code\n{\n")
		for _, c := range codes {
			detail := strings.TrimSpace(c.Comment)
			note := c.Origin
			if detail != "" {
				note += ": " + detail
			}
			fmt.Fprintf(&sb, "    /** %s */\n    public const %s = '%s';\n", note, c.Code, c.Code)
		}
		sb.WriteString("}\n")
	case "php-extension":
		// The block of Polyspec\Orm\Code in the one stub of the extension, between phpExtensionBegin and
		// phpExtensionEnd: gen_stub.php writes src/polyspec_orm_arginfo.h from the stub (make php-ext-arginfo), so the
		// extension registers the same constants as the PHP client's Code. The rest of the stub is kept as it is.
		sb.WriteString(phpExtensionBegin + "\n\nnamespace Polyspec\\Orm;\n\n/** Error codes shared by the engine and every executor (docs/spec/errors.yaml). */\nfinal class Code\n{\n")
		for _, c := range codes {
			detail := strings.TrimSpace(c.Comment)
			note := c.Origin
			if detail != "" {
				note += ": " + detail
			}
			fmt.Fprintf(&sb, "    /** %s */\n    public const string %s = '%s';\n", note, c.Code, c.Code)
		}
		sb.WriteString("}\n" + phpExtensionEnd + "\n")
	case "rust":
		sb.WriteString("//! Code generated by orm-gen errors from docs/spec/errors.yaml; DO NOT EDIT.\n//! Error codes shared by the engine and every executor (docs/spec/errors.yaml).\n\n")
		for _, c := range codes {
			detail := strings.TrimSpace(c.Comment)
			note := c.Origin
			if detail != "" {
				note += ": " + detail
			}
			fmt.Fprintf(&sb, "/// %s\npub const %s: &str = %q;\n", note, c.Code, c.Code)
		}
	case "typescript":
		sb.WriteString("// Code generated by orm-gen errors from docs/spec/errors.yaml; DO NOT EDIT.\n// Error codes shared by the engine and every executor (docs/spec/errors.yaml).\n\n")
		for _, c := range codes {
			detail := strings.TrimSpace(c.Comment)
			note := c.Origin
			if detail != "" {
				note += ": " + detail
			}
			fmt.Fprintf(&sb, "// %s\nexport const %s = '%s';\n", note, c.Code, c.Code)
		}
	case "python":
		sb.WriteString("# Code generated by orm-gen errors from docs/spec/errors.yaml; DO NOT EDIT.\n# Error codes shared by the engine and every executor (docs/spec/errors.yaml).\n\n")
		for _, c := range codes {
			detail := strings.TrimSpace(c.Comment)
			note := c.Origin
			if detail != "" {
				note += ": " + detail
			}
			fmt.Fprintf(&sb, "# %s\n%s = \"%s\"\n", note, c.Code, c.Code)
		}
	default:
		fail(fmt.Errorf("unknown lang %q", *lang))
	}
	body := []byte(sb.String())
	if *lang == "php-extension" {
		stub, err := os.ReadFile(*out)
		if err != nil {
			fail(err)
		}
		body, err = replaceBlock(string(stub), sb.String())
		if err != nil {
			fail(fmt.Errorf("%s: %w", *out, err))
		}
	}
	if *lang == "go" {
		formatted, err := format.Source(body)
		if err != nil {
			fail(err)
		}
		body = formatted
	}
	if err := os.WriteFile(*out, body, 0o644); err != nil {
		fail(err)
	}
	fmt.Fprintf(os.Stderr, "orm-gen: %d codes → %s\n", len(codes), *out)
}

// constantName converts an UPPER_SNAKE error code into a PascalCase Go constant name.
func constantName(code string) string {
	var b strings.Builder
	for _, part := range strings.Split(strings.ToLower(code), "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

// The lines that bound the block of the error codes in the stub of the PHP extension.
const (
	phpExtensionBegin = "// Code generated by orm-gen errors from docs/spec/errors.yaml; DO NOT EDIT."
	phpExtensionEnd   = "// End of the code generated by orm-gen errors."
)

// replaceBlock returns stub with its block from the line phpExtensionBegin through the line phpExtensionEnd replaced by
// block, which ends with a line end; the stub must hold each line exactly once, the end after the begin.
func replaceBlock(stub, block string) ([]byte, error) {
	begin, end := strings.Count(stub, phpExtensionBegin+"\n"), strings.Count(stub, phpExtensionEnd+"\n")
	if begin != 1 || end != 1 {
		return nil, fmt.Errorf("the stub holds the line %q %d times and the line %q %d times, not once each", phpExtensionBegin, begin, phpExtensionEnd, end)
	}
	from, to := strings.Index(stub, phpExtensionBegin+"\n"), strings.Index(stub, phpExtensionEnd+"\n")+len(phpExtensionEnd)+1
	if to < from {
		return nil, fmt.Errorf("the line %q comes before the line %q", phpExtensionEnd, phpExtensionBegin)
	}
	return []byte(stub[:from] + block + stub[to:]), nil
}
