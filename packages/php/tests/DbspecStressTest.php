<?php
declare(strict_types=1);
// The shared 2000-table, 60000-column, 10000-foreign-key document from
// tests/dbspec/stress.mts: parse and emit times, emit(parse(doc)) === doc and
// two identical emissions, under the configured memory_limit.
require_once __DIR__ . '/case_clock.php';

use PHPUnit\Framework\Assert;
use PHPUnit\Framework\Attributes\Group;
use PHPUnit\Framework\Attributes\Large;
use PHPUnit\Framework\TestCase;

/** Base work of the stress document: for each byte, computes h = h*31 + b (mod 2^32) in order. */
function dbspec_stress_reference_scan(string $text): int
{
    $h = 0;
    $length = strlen($text);
    for ($i = 0; $i < $length; $i++) {
        $h = ($h * 31 + ord($text[$i])) & 0xFFFFFFFF;
    }
    return $h;
}

// A benchmark of make dbspec-stress-bench (group bench): its measurements go to stderr.
#[Large]
#[Group('bench')]
final class DbspecStressTest extends TestCase
{
    public function test_stress(): void
    {
        // The CPU baseline for the stress case is 60 s. It covers document creation (one node process), five parses, and two emits. Warns if exceeded.
        $clock = cpuCaseBegin(60.0);
        $started = $clock[0];
        fwrite(STDERR, 'memoryLimit=' . ini_get('memory_limit') . "\n");
        $root = dirname(__DIR__, 3);
        $process = proc_open(['node', "$root/tests/dbspec/stress.mts"], [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes);
        Assert::assertTrue(is_resource($process), 'node tests/dbspec/stress.mts did not start');
        $text = stream_get_contents($pipes[1]);
        $errors = stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        $status = proc_close($process);
        Assert::assertFalse($status !== 0 || $text === false || $text === '', "node tests/dbspec/stress.mts failed with status $status: $errors");
        fwrite(STDERR, 'generated bytes=' . strlen($text) . "\n");

        $parses = [];
        for ($i = 0; $i < 5; $i++) {
            $result = null;
            $parseStarted = caseClockStart();
            $result = Polyspec\Orm\Dbspec\Dbspec::parse($text, []);
            [$parseCpuMs, $parseWallMs] = caseClockElapsed($parseStarted);
            fwrite(STDERR, "parse cpuMs=$parseCpuMs wallMs=$parseWallMs" . "\n");
            $parses[] = $parseCpuMs;
        }
        sort($parses);
        $parseMs = $parses[2];
        // The base work is a loop that updates a checksum for each byte of the same document. It is measured in the same process with the same clock, and
        // prints the ratio to the parse time (docs/spec/dbspec.md, Verification).
        $references = [];
        for ($i = 0; $i < 5; $i++) {
            $referenceStarted = caseClockStart();
            $referenceSum = dbspec_stress_reference_scan($text);
            $references[] = caseClockElapsed($referenceStarted)[0];
        }
        sort($references);
        fwrite(STDERR, sprintf('reference cpu medianMs=%.3f ratio=%.2f sum=%d', $references[2], $parseMs / $references[2], $referenceSum) . "\n");
        if ($result->document === null) {
            $first = array_slice($result->diagnostics, 0, 5);
            throw new RuntimeException('Stress document rejected: ' . implode('; ', array_map(static fn($d) => "{$d->line}:{$d->column} {$d->rule} {$d->message}", $first)));
        }
        $document = $result->document;
        Assert::assertSame(2000, count($document->tables), 'Stress document table count ' . count($document->tables));
        $columns = 0;
        $foreignKeys = 0;
        foreach ($document->tables as $table) {
            $columns += count($table->columns);
            $foreignKeys += count($table->foreignKeys);
        }
        Assert::assertFalse($columns !== 60000 || $foreignKeys !== 10000, "Stress document has $columns columns and $foreignKeys foreign keys");
        fwrite(STDERR, "parsed cpu minMs={$parses[0]} medianMs=$parseMs maxMs={$parses[4]}" . "\n");

        $emitStarted = caseClockStart();
        $first = Polyspec\Orm\Dbspec\Dbspec::emit($document);
        $emitMs = caseClockElapsed($emitStarted)[0];
        $second = Polyspec\Orm\Dbspec\Dbspec::emit($document);
        Assert::assertSame($text, $first, 'emit(parse(doc)) differs from the stress document');
        Assert::assertSame($first, $second, 'Two emissions differ');
        fwrite(STDERR, "emitted emitMs=$emitMs" . "\n");

        // docs/spec/dbspec.md, "Verification": the ratio of the median parse CPU time to the median CPU time of the reference work
        // is printed, and a ratio above the documented reference value prints a warning. A measurement never fails the test.
        $referenceRatio = 11.0;
        $ratio = $parseMs / $references[2];
        $machine = sprintf('%s %s, PHP %s', PHP_OS_FAMILY, php_uname('m'), PHP_VERSION);
        fwrite(STDERR, sprintf('parse ratio %.2f to the reference on %s (reference ratio %.1f)', $ratio, $machine, $referenceRatio) . "\n");
        if ($ratio > $referenceRatio) {
            fwrite(STDERR, 'WARNING ' . sprintf(
                'dbspec_stress median parse CPU of %.3f ms is %.2f times the reference CPU of %.3f ms, above the reference ratio %.1f (docs/spec/dbspec.md, Verification); machine %s',
                $parseMs, $ratio, $references[2], $referenceRatio, $machine,
            ) . "\n");
        }
        fwrite(STDERR, "parseMs=$parseMs emitMs=$emitMs peakBytes=" . memory_get_peak_usage(true) . "\n");
        cpuCaseEnd('dbspec_stress', $clock);
    }
}
