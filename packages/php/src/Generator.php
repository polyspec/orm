<?php

declare(strict_types=1);

namespace Polyspec\Orm;

/**
 * Writes one model class per entity with typed column accessors, the model
 * metadata and the query methods that the schema enumerates, plus bootstrap.php,
 * which registers the classes. The query methods are the condition method of
 * every column and the tuple method of every key prefix of two or more columns,
 * the column methods addColumn, removeColumn, groupBy, keyName, orderBy…Asc and
 * orderBy…Desc, and of a numeric column plus, minus, sum and avg, and forceIndex
 * of every index. Each runs the chain of its name through Model::__call. Every
 * other method name, such as an operator chain, a finder or a join, is resolved
 * at call time by Model with the grammar of the DSL.
 */
final class Generator
{
    public const MARKER = '// Code generated by orm-gen; DO NOT EDIT.';

    /**
     * The public and protected methods of Model, which every generated model inherits: a generated method with the
     * same name would replace one. They are read from the class, so a method added to Model is reserved here
     * without a second list.
     * @return list<string>
     */
    private static function modelMethods(): array
    {
        return array_map(
            static fn(\ReflectionMethod $r): string => $r->getName(),
            (new \ReflectionClass(Model::class))->getMethods(
                \ReflectionMethod::IS_PUBLIC | \ReflectionMethod::IS_PROTECTED)
        );
    }

    /** Column naming rules of the DSL. */
    private const RESERVED_SEGMENTS = ['and', 'or', 'with', 'gt', 'lt', 'ge', 'le', 'eq', 'ne', 'lk', 'lb',
        'between', 'tuple'];
    private const RESERVED_PREFIXES = ['and', 'or', 'get', 'set', 'new', 'plus', 'minus', 'order_by',
        'group_by', 'tuple', 'gt', 'lt', 'ge', 'le', 'eq', 'ne', 'lk', 'lb', 'between'];
    private const RESERVED_COLUMNS = ['and', 'or', 'not', 'get', 'gets', 'gets_page', 'get_query', 'limit',
        'alias', 'connect', 'create', 'creates', 'update', 'delete', 'restore', 'save', 'on', 'random'];

    /** Generates the model of $m into $outDir and changes the files generated before. */
    public static function generate(RuntimeModel $m, string $outDir, string $namespace, array $scan = []): void
    {
        $files = self::files($m, $namespace, $scan);
        if (!is_dir($outDir) && !mkdir($outDir, 0o755, true)) {
            throw new OrmException(Code::CONFIG, "cannot create $outDir");
        }
        foreach (self::generated($outDir) as $file) {
            unlink($file);
        }
        foreach ($files as $name => $body) {
            self::write("$outDir/$name", $body);
        }
    }

    /**
     * Generates the model of $m without writing it, and for each generated file in $outDir that differs,
     * is missing, or is extra, returns one line in path order.
     * @return list<string>
     */
    public static function check(RuntimeModel $m, string $outDir, string $namespace, array $scan = []): array
    {
        $files = self::files($m, $namespace, $scan);
        $lines = [];
        foreach ($files as $name => $body) {
            $path = "$outDir/$name";
            if (!is_file($path)) {
                $lines[$path] = "missing: $path";
            } elseif (file_get_contents($path) !== $body) {
                $lines[$path] = "differs: $path";
            }
        }
        foreach (self::generated($outDir) as $path) {
            if (!array_key_exists(basename($path), $files)) {
                $lines[$path] = "extra: $path";
            }
        }
        ksort($lines, SORT_STRING);
        return array_values($lines);
    }

    /** @return list<string> the PHP files of $outDir that hold the generated marker */
    private static function generated(string $outDir): array
    {
        return array_values(array_filter(
            glob($outDir . '/*.php') ?: [],
            static fn(string $file): bool => str_contains((string) file_get_contents($file), self::MARKER),
        ));
    }

    /** @return array<string, string> the generated file bodies by file name */
    private static function files(RuntimeModel $m, string $namespace, array $scan = []): array
    {
        foreach ($m->entities as $e) {
            foreach ($e['columns'] as $c) {
                self::checkColumnName($e['entity'], $c['name']);
            }
        }
        foreach ($m->entities as $e) {
            self::checkNames($e);
        }
        $tags = $scan === [] ? [] : self::scanTags($m, $namespace, $scan);
        $files = [];
        $external = $m->externalText !== '';
        $boot = "<?php\n" . self::MARKER . "\ndeclare(strict_types=1);\n\nnamespace $namespace;\n\n"
            . "use Polyspec\\Orm\\Config;\nuse Polyspec\\Orm\\Db;\nuse Polyspec\\Orm\\Orm;\n"
            . "use Polyspec\\Orm\\Registry;\nuse Polyspec\\Orm\\Schema;\n\n"
            . "/** The manifestHash of the document set the models were generated from. */\n"
            . "const MANIFEST_HASH = " . self::str($m->manifestHash) . ";\n\n"
            . "/** The manifest text of the document set the models were generated from. */\n"
            . "const MANIFEST_TEXT = " . self::str($m->manifestText) . ";\n\n"
            // The bootstrap of a set that does not use external documents does not write external text,
            // so it is unchanged.
            . ($external
                ? "/** The tables that the set uses from external documents, which other sets own. */\n"
                    . "const EXTERNAL_TEXT = " . self::str($m->externalText) . ";\n\n"
                : '')
            . "/** The generated schema value: install takes it to create the tables and register the set. */\n"
            . "function schema(): Schema\n{\n    return new Schema(MANIFEST_TEXT, MANIFEST_HASH"
            . ($external ? ', EXTERNAL_TEXT' : '') . ");\n}\n\n"
            . "/** Opens the database selected by the DSN URI and "
            . "registers the set of these models on the connection. */\n"
            . "function connect(string \$dsn, Config \$config): Db\n{\n"
            . "    return Orm::connectSchema(\$dsn, schema(), \$config);\n}\n\n"
            . "Registry::generated(MANIFEST_HASH, MANIFEST_TEXT" . ($external ? ', EXTERNAL_TEXT' : '') . ");\n";
        foreach ($m->entities as $e) {
            $class = self::pascal($e['entity']);
            if (isset($files["$class.php"])) {
                throw new OrmException(Code::SCHEMA_INVALID,
                    "entities {$e['entity']} and another entity generate the class $class");
            }
            $files["$class.php"] = self::model($e, $class, $namespace, $m->manifestHash, $tags[$class] ?? []);
            $boot .= "Registry::register($class::class);\n";
        }
        $files['bootstrap.php'] = $boot;
        return $files;
    }

    private static function write(string $path, string $body): void
    {
        if (file_put_contents($path, $body) === false) {
            throw new OrmException(Code::CONFIG, "cannot write $path");
        }
    }

    /** @param list<string> $tags the @method tags of the scanned chain methods */
    private static function model(array $e, string $class, string $namespace, string $hash, array $tags = []): string
    {
        $name = $e['entity'];
        $b = "<?php\n" . self::MARKER . "\ndeclare(strict_types=1);\n\nnamespace $namespace;\n\n"
            . "use Polyspec\\Orm\\Model;\n\n" . self::classComment($name, $tags)
            . "\nfinal class $class extends Model\n{\n";
        // meta() is the manifest_hash of the document set that made the entity and its model.
        $b .= "    public static function meta(): array\n    {\n        return "
            . self::export($e + ['manifest_hash' => $hash], 2) . ";\n    }\n";
        foreach ($e['columns'] as $c) {
            $p = self::pascal($c['name']);
            $styled = RuntimeModel::styled($c);
            $t = $styled ? '\\Polyspec\\Orm\\StyledValue' : self::type($c);
            $nt = !$styled && $c['nullable'] ? "?$t" : $t;
            $b .= "\n    public function get$p(): $nt\n    {\n        return \$this->readColumn("
                . self::str($c['name']) . ");\n    }\n";
            // A date, time or datetime setter takes the text form, as the loaded value does (T189).
            $param = $t === '\\DateTimeImmutable' ? ($c['nullable'] ? '?string' : 'string') : $nt;
            $b .= "\n    public function set$p($param \$v): static\n    {\n        return \$this->writeColumn("
                . self::str($c['name']) . ", \$v);\n    }\n";
        }
        return $b . self::queryMethods($e) . "}\n";
    }

    /**
     * The query methods that the schema enumerates. Each is a typed method whose body runs the chain of its name
     * through Model::__call, so that a static analyser sees the method and the model resolves it as before.
     */
    private static function queryMethods(array $e): string
    {
        $methods = self::queryMethodMap($e);
        return $methods === [] ? '' : "\n" . implode("\n", $methods);
    }

    /** @return array<string, string> the declaration of each query method by name, ordered by name */
    private static function queryMethodMap(array $e): array
    {
        $methods = [];
        $chain = static fn(string $name, string $params, string $doc = ''): string => $doc
            . "    public function $name($params): static\n    {\n        \$this->__call("
            . self::str($name) . ", func_get_args());\n        return \$this;\n    }\n";
        foreach ($e['columns'] as $c) {
            $p = self::pascal($c['name']);
            $methods[self::camel($c['name'])] = $chain(
                self::camel($c['name']),
                'mixed $value, mixed ...$compared',
                "    /** The condition of {$c['name']}: a value, a list, a value function, a model, "
                . "or a column function and its compared value. */\n"
            );
            foreach (['addColumn', 'removeColumn', 'groupBy', 'keyName'] as $prefix) {
                $methods[$prefix . $p] = $chain($prefix . $p, '');
            }
            $methods["orderBy{$p}Asc"] = $chain("orderBy{$p}Asc", '\\Polyspec\\Orm\\Func ...$fn');
            $methods["orderBy{$p}Desc"] = $chain("orderBy{$p}Desc", '\\Polyspec\\Orm\\Func ...$fn');
            if (RuntimeModel::numeric($c)) {
                $n = self::type($c) === 'string' ? 'string' : 'int|float';
                $methods["plus$p"] = $chain("plus$p", "$n \$n");
                $methods["minus$p"] = $chain("minus$p", "$n \$n");
                $methods["sum$p"] = $chain("sum$p", '');
                $methods["avg$p"] = $chain("avg$p", '');
            }
        }
        foreach ([$e['pk'], ...array_values($e['unique']), ...array_values($e['indexes'])] as $columns) {
            for ($k = 2; $k <= count($columns); $k++) {
                $name = 'tuple' . implode('With', array_map(self::pascal(...), array_slice($columns, 0, $k)));
                $methods[$name] ??= $chain($name, 'array $values',
                    '    /** @param list<list<mixed>> $values */' . "\n");
            }
        }
        foreach (array_keys($e['indexes']) as $index) {
            $name = 'forceIndex' . self::pascal((string) $index);
            $methods[$name] = $chain($name, '');
        }
        ksort($methods, SORT_STRING);
        return $methods;
    }

    /** The comment of a model class; the @method tags follow the description. */
    private static function classComment(string $name, array $tags): string
    {
        if ($tags === []) {
            return "/** A $name model or row. */";
        }
        return "/**\n * A $name model or row.\n *\n"
            . implode('', array_map(static fn(string $t): string => " * $t\n", $tags)) . ' */';
    }

    /**
     * The @method tags of the chain methods that the scanned sources call on each model, by class name. A name that
     * no column, chain or operator accepts, and a call with an argument count the chain does not take,
     * fail with CONFIG.
     * @param list<string> $scan
     * @return array<string, list<string>>
     */
    private static function scanTags(RuntimeModel $m, string $namespace, array $scan): array
    {
        $classes = [];
        $metas = [];
        foreach ($m->entities as $e) {
            $class = self::pascal($e['entity']);
            $classes[] = $class;
            $metas[] = $e + ['manifest_hash' => $m->manifestHash, 'class' => ltrim($namespace, '\\') . '\\' . $class];
        }
        $sites = [];
        $calls = Scan::calls($scan, $namespace, $classes, $sites);
        $used = [];
        foreach ($calls as $names) {
            foreach (array_keys($names) as $name) {
                $used[$name] = true;
            }
        }
        $declare = new ChainDeclare($metas);
        $problems = [];
        $tags = [];
        // A getter that a scanned call names is refused only when no class the call may be on attaches it:
        // a class of the call that lacks the getter is not an error, since the call runs on the class that
        // has it (docs/spec/dsl.md, the scan).
        $entities = array_column($metas, 'entity');
        foreach ($sites as $site) {
            $name = $site['name'];
            $count = $site['count'];
            $key = substr($name, 3);
            $declaresAny = false;
            $accepts = false;
            $declaredBy = null;
            foreach ($metas as $meta) {
                if (!in_array(self::pascal($meta['entity']), $site['classes'], true)) {
                    continue;
                }
                $static = array_fill_keys([...array_map('strtolower', self::modelMethods()),
                    ...array_map('strtolower', array_keys(self::queryMethodMap($meta)))], true);
                foreach ($meta['columns'] as $c) {
                    $p = self::pascal($c['name']);
                    $static[strtolower("get$p")] = $static[strtolower("set$p")] = true;
                }
                if (isset($static[strtolower($name)])) {
                    $declaresAny = $accepts = true;
                    continue;
                }
                $declaration = $declare->declare($meta, $name);
                if ($declaration !== null) {
                    $declaresAny = true;
                    $declaredBy ??= [self::pascal($meta['entity']), $declaration];
                    if ($count === null || ($count >= $declaration['min'] && $count <= $declaration['max'])) {
                        $accepts = true;
                    }
                    continue;
                }
                if (self::namedGetter($name, $key, $entities, $used)) {
                    $declaresAny = $accepts = true;
                }
            }
            if (!$declaresAny) {
                $problems[] = str_starts_with($name, 'get') && strlen($name) > 3 && ctype_upper($name[3])
                    ? "{$site['classes'][0]}.$name is called, but no alias$key, new$key or addColumn call attaches it"
                    : "{$site['classes'][0]}.$name is not a model method: no column, chain or operator accepts it";
            } elseif (!$accepts && $declaredBy !== null) {
                [$class, $declaration] = $declaredBy;
                $takes = $declaration['min'] === $declaration['max']
                    ? (string) $declaration['min'] : "{$declaration['min']} to {$declaration['max']}";
                $problems[] = "$class.$name takes $takes argument"
                    . ($declaration['max'] === 1 ? '' : 's') . ", called with $count";
            }
        }
        foreach ($metas as $meta) {
            $class = self::pascal($meta['entity']);
            $static = array_fill_keys([...array_map('strtolower', self::modelMethods()),
                ...array_map('strtolower', array_keys(self::queryMethodMap($meta)))], true);
            foreach ($meta['columns'] as $c) {
                $p = self::pascal($c['name']);
                $static[strtolower("get$p")] = $static[strtolower("set$p")] = true;
            }
            $found = [];
            foreach ($calls[$class] ?? [] as $name => $counts) {
                if (isset($static[strtolower($name)])) {
                    continue;
                }
                $declaration = $declare->declare($meta, $name);
                if ($declaration === null) {
                    // A name that no class declares is refused by the group check above, with the classes of its call.
                    if (self::namedGetter($name, substr($name, 3), array_column($metas, 'entity'), $used)) {
                        $found[$name] = ChainDeclare::getter($name);
                    }
                    continue;
                }
                $found[$name] = ChainDeclare::tag($name, $declaration);
            }
            ksort($found, SORT_STRING);
            $tags[$class] = array_values($found);
        }
        if ($problems !== []) {
            sort($problems, SORT_STRING);
            throw new OrmException(Code::CONFIG, implode('; ', $problems));
        }
        return $tags;
    }

    /**
     * Whether `get<Key>` reads a value that the sources name: the relation result `<Entity>Model` or `<Entity>Models`,
     * or a name that a scanned alias, new, or addColumn call adds.
     * @param list<array> $metas
     * @param array<string, true> $used
     */
    /** @param list<string> $entities the entity names of the owned tables and of the external tables that are used */
    private static function namedGetter(string $name, string $key, array $entities, array $used): bool
    {
        if (!str_starts_with($name, 'get') || strlen($name) < 4 || !ctype_upper($name[3])) {
            return false;
        }
        foreach ($entities as $entity) {
            $pascal = self::pascal($entity);
            if ($key === $pascal . 'Model' || $key === $pascal . 'Models') {
                return true;
            }
        }
        if (isset($used["alias$key"]) || isset($used["new$key"]) || isset($used["addColumn$key"])) {
            return true;
        }
        foreach (array_keys($used) as $n) {
            if (str_starts_with($n, 'addColumn') && str_ends_with($n, "Alias$key")) {
                return true;
            }
        }
        return false;
    }

    /**
     * A PHP array literal. An array whose values are scalars or only lists of scalars is written on one line;
     * other arrays are written one line per element.
     */
    private static function export(mixed $v, int $depth): string
    {
        if (is_bool($v)) {
            return $v ? 'true' : 'false';
        }
        if (is_int($v)) {
            return (string) $v;
        }
        if (is_string($v)) {
            return self::str($v);
        }
        if (!is_array($v)) {
            throw new OrmException(Code::INTERNAL, 'the runtime model holds a ' . get_debug_type($v));
        }
        $list = array_is_list($v);
        $item = static fn(int|string $k, mixed $x, int $d): string =>
            ($list ? '' : self::export((string) $k, $d) . ' => ') . self::export($x, $d);
        $flat = true;
        foreach ($v as $x) {
            if (is_array($x) && ($x !== [] && (!array_is_list($x) || array_filter($x, 'is_array') !== []))) {
                $flat = false;
            }
        }
        if ($flat) {
            $parts = [];
            foreach ($v as $k => $x) {
                $parts[] = $item($k, $x, $depth + 1);
            }
            return '[' . implode(', ', $parts) . ']';
        }
        $pad = str_repeat('    ', $depth + 1);
        $out = "[\n";
        foreach ($v as $k => $x) {
            $out .= $pad . $item($k, $x, $depth + 1) . ",\n";
        }
        return $out . str_repeat('    ', $depth) . ']';
    }

    public static function pascal(string $s): string
    {
        return implode('', array_map(ucfirst(...), explode('_', $s)));
    }

    private static function camel(string $s): string
    {
        return lcfirst(self::pascal($s));
    }

    private static function str(string $s): string
    {
        return "'" . strtr($s, ['\\' => '\\\\', "'" => "\\'"]) . "'";
    }

    /** @param list<string> $items */
    private static function list(array $items): string
    {
        return '[' . implode(', ', array_map(self::str(...), $items)) . ']';
    }

    /** The PHP value type of a column with no codec, or with only aes, hex, or ip stages. */
    private static function type(array $c): string
    {
        if ($c['codec'] !== []) {
            return 'string';
        }
        return match ($c['type']) {
            'i16', 'i32', 'i64' => 'int',
            'f64' => 'float',
            'bool' => 'bool',
            'date', 'datetime' => '\\DateTimeImmutable',
            default => 'string',
        };
    }

    private static function checkColumnName(string $entity, string $n): void
    {
        $fail = static fn(string $msg): OrmException => new OrmException(Code::SCHEMA_INVALID, "$entity.$n: $msg");
        if (preg_match('/^[a-z][a-z0-9_]*$/', $n) !== 1) {
            throw $fail("column name must be snake_case: $n");
        }
        if (str_contains($n, '__')) {
            throw $fail("column name may not contain '__': $n");
        }
        foreach (explode('_', $n) as $segment) {
            if (in_array($segment, self::RESERVED_SEGMENTS, true)) {
                throw $fail("column name may not contain the segment \"$segment\": $n");
            }
        }
        if (in_array($n, self::RESERVED_COLUMNS, true)) {
            throw $fail("column name is a reserved method name: $n");
        }
        foreach (self::RESERVED_PREFIXES as $p) {
            if ($n === $p || str_starts_with($n, $p . '_')) {
                throw $fail("column name may not start with \"$p\": $n");
            }
        }
    }

    /** Rejects a column whose accessor or condition method is another method of the model. */
    private static function checkNames(array $e): void
    {
        $names = [];
        foreach (self::modelMethods() as $n) {
            $names[strtolower($n)] = $n;
        }
        $fixed = $names;
        foreach ($e['columns'] as $c) {
            $p = self::pascal($c['name']);
            $derived = ['get', 'set', 'addColumn', 'removeColumn', 'groupBy', 'keyName'];
            if (RuntimeModel::numeric($c)) {
                array_push($derived, 'plus', 'minus', 'sum', 'avg');
            }
            foreach ($derived as $prefix) {
                $names[strtolower($prefix . $p)] = $prefix . $p;
            }
            $names[strtolower("orderBy{$p}Asc")] = "orderBy{$p}Asc";
            $names[strtolower("orderBy{$p}Desc")] = "orderBy{$p}Desc";
        }
        foreach ($e['indexes'] as $index => $_) {
            $names[strtolower('forceIndex' . self::pascal((string) $index))] =
                'forceIndex' . self::pascal((string) $index);
        }
        foreach ($e['columns'] as $c) {
            $p = self::pascal($c['name']);
            foreach (["get$p", "set$p"] as $accessor) {
                if (isset($fixed[strtolower($accessor)])) {
                    throw new OrmException(Code::SCHEMA_INVALID,
                        "{$e['entity']}.{$c['name']}: $accessor is a fixed model method");
                }
            }
            if (isset($names[strtolower($p)])) {
                throw new OrmException(Code::SCHEMA_INVALID,
                    "{$e['entity']}.{$c['name']}: the condition method " . self::camel($c['name'])
                    . ' is also the model method ' . $names[strtolower($p)]);
            }
        }
    }
}
