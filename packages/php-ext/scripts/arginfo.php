<?php
declare(strict_types=1);

// Makes src/<name>_arginfo.h from each stubs/<name>.stub.php (orm_dbspec and code) with gen_stub.php. gen_stub cannot
// write array constants, so it is made from a copy without the `public const array` line; that constant is registered by src/orm_dbspec.c
// (the declaration check compares the whole stub with the extension's Reflection).
//
// Usage: php packages/php-ext/scripts/arginfo.php <gen_stub.php> write|check
// write rewrites the header, and check exits with 1 if the regenerated header differs from the saved one. gen_stub.php uses the
// PHP-Parser in the same directory, and downloads it if it is absent, so check that it is present first (make orm-install-php-extension-tools).

[, $genStub, $mode] = $argv + [null, '', ''];
if ($genStub === '' || !in_array($mode, ['write', 'check'], true)) {
    fwrite(STDERR, "usage: php packages/php-ext/scripts/arginfo.php <gen_stub.php> write|check\n");
    exit(2);
}
if (!is_file($genStub)) {
    fwrite(STDERR, "$genStub does not exist; run make orm-install-php-extension-tools, which copies gen_stub.php of the PHP installation and its PHP-Parser\n");
    exit(1);
}
if (glob(dirname($genStub) . '/PHP-Parser-*', GLOB_ONLYDIR) === []) {
    fwrite(STDERR, dirname($genStub) . " has no PHP-Parser, which gen_stub.php would download; run make orm-install-php-extension-tools\n");
    exit(1);
}
$root = dirname(__DIR__);

/** generate runs gen_stub.php on $text as stubs/$name.stub.php and returns the header it writes. */
function generate(string $genStub, string $name, string $text): string
{
    $work = sys_get_temp_dir() . "/orm-dbspec-arginfo-$name-" . getmypid();
    if (!mkdir($work)) {
        fwrite(STDERR, "cannot create $work\n");
        exit(1);
    }
    try {
        file_put_contents("$work/$name.stub.php", $text);
        $command = [PHP_BINARY, $genStub, "$work/$name.stub.php"];
        $process = proc_open($command, [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes);
        $out = stream_get_contents($pipes[1]);
        $err = stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);
        if (proc_close($process) !== 0 || !is_file("$work/{$name}_arginfo.h")) {
            fwrite(STDERR, implode(' ', $command) . " failed:\n$out$err");
            exit(1);
        }
        return file_get_contents("$work/{$name}_arginfo.h");
    } finally {
        foreach (glob("$work/*") as $file) {
            unlink($file);
        }
        rmdir($work);
    }
}

// orm_dbspec.stub.php has array constants, which src/orm_dbspec.c registers; code.stub.php is generated by orm-gen errors and has none.
$stub = file_get_contents("$root/stubs/orm_dbspec.stub.php");
$filtered = preg_replace('/^    public const array [A-Z_]+ = .*;\n/m', '', $stub, -1, $removed);
if ($removed === 0) {
    fwrite(STDERR, "the stub declares no array constant; update packages/php-ext/scripts/arginfo.php and src/orm_dbspec.c together\n");
    exit(1);
}
$headers = [
    'orm_dbspec' => generate($genStub, 'orm_dbspec', $filtered),
    'code' => generate($genStub, 'code', file_get_contents("$root/stubs/code.stub.php")),
];
$failed = false;
foreach ($headers as $name => $generated) {
    $target = "$root/src/{$name}_arginfo.h";
    if ($mode === 'write') {
        file_put_contents("$target.tmp", $generated);
        rename("$target.tmp", $target);
        echo "wrote src/{$name}_arginfo.h\n";
    } elseif (!is_file($target) || file_get_contents($target) !== $generated) {
        fwrite(STDERR, "src/{$name}_arginfo.h differs from stubs/$name.stub.php; run make php-extension-arginfo, which writes it with gen_stub.php\n");
        $failed = true;
    } else {
        echo "src/{$name}_arginfo.h is generated from stubs/$name.stub.php\n";
    }
}
echo "$removed array constants of stubs/orm_dbspec.stub.php are left to src/orm_dbspec.c\n";
exit($failed ? 1 : 0);
