/// The database part of a recipe without a database (FCV-3).
pub const NONE: &str = "none";

/// The schema of the request validation ops: the bench model, whose manifest the requests are checked against.
const IR_VALIDATE_SCHEMA: &str = "contracts/fixtures/bench/bench.dbs";

/// The dialects of the planner op, each with the name of its expect.
const PLAN_DIALECTS: [(&str, engine::Dialect); 3] =
    [("mysql", engine::Dialect::MySql), ("postgres", engine::Dialect::Postgres), ("sqlite", engine::Dialect::Sqlite)];

/// What a step produced: its value, or the code and message of its error.
type Outcome = Result<Produced, (String, String)>;

#[derive(Clone)]
enum Produced {
    /// The value a decode or a host decode read.
    Read(Val),
    /// The cell an encode, a host encode or a blind index wrote.
    Written(Param),
    /// The document that a dbspec parse binds.
    Document(Document),
    /// The plan that a dbspec parse_plan binds.
    Plan(dbspec::Plan),
    /// The plain JSON result of a Mermaid op (FCV-4): the mermaid and the dropped objects of an export, or the document,
    /// the dropped objects, the errors or the skeleton check of an import.
    Plain(Value),
}

/// The repository root and the text of the recipe at `path`, relative to it, after the key check of the recipe file.
fn recipe_text(path: &str) -> (PathBuf, String) {
    let root = polyspec_orm_testcase::manifest_dir().join("../../..");
    let text = match std::fs::read_to_string(root.join(path)) {
        Ok(text) => text,
        Err(error) => panic!("recipe {path}: {error}"),
    };
    if let Err(error) = crate::recipe_keys::check_keys(path, &text) {
        panic!("{error}");
    }
    (root, text)
}

/// One trial for each case of the recipe at `path`, relative to the repository root, on `database`, named
/// `<entry>::<case id>`.
pub fn trials(entry: &str, path: &str, database: &str) -> Vec<polyspec_orm_testcase::Trial> {
    assert_eq!(database, NONE, "recipe {path}: database {database} has no case database in this helper");
    let (root, text) = recipe_text(path);
    let recipe: Value = match serde_json::from_str(&text) {
        Ok(recipe) => recipe,
        Err(error) => panic!("recipe {path}: {error}"),
    };
    let Some(cases) = recipe["cases"].as_array() else { panic!("recipe {path} has no cases") };
    // The documents of a dbspec step are relative to the directory of the recipe file.
    let dir: PathBuf = root.join(path).parent().map_or_else(|| root.clone(), Path::to_path_buf);
    cases
        .iter()
        .map(|case| {
            let case = case.clone();
            let (path, database, dir) = (path.to_owned(), database.to_owned(), dir.clone());
            let id = case["id"].as_str().unwrap_or_default().to_owned();
            polyspec_orm_testcase::trial(format!("{entry}::{id}"), polyspec_orm_testcase::COMPUTE, move || {
                let mut bound = HashMap::new();
                let steps = case["steps"].as_array().cloned().unwrap_or_default();
                for (index, step) in steps.iter().enumerate() {
                    if let Err(failure) = run(step, &mut bound, &database, &dir) {
                        panic!("recipe {path} case {id} step {index} ({}) on {database}: {failure}", step["op"]);
                    }
                }
            })
        })
        .collect()
}

/// The DSN that a model.connect opens (FCV-4): the case database, unless its dsn is "case-socket" or the DSN text of the step.
pub fn connect_dsn(dsn: Option<&str>, database: &str, case_dsn: &str, socket: Option<&str>) -> Result<String, String> {
    match dsn {
        None | Some("case") => Ok(case_dsn.to_owned()),
        Some("case-socket") => {
            if database != "mysql" {
                return Err(format!("dsn case-socket needs mysql, not {database}"));
            }
            let socket = socket.filter(|s| !s.is_empty()).ok_or("dsn case-socket: ORM_TEST_MYSQL_SOCKET is unset; run make orm-test-servers")?;
            let not_mysql = || format!("dsn case-socket: the case DSN {case_dsn} is not a mysql DSN");
            let rest = case_dsn.strip_prefix("mysql://").ok_or_else(not_mysql)?;
            let (user, rest) = rest.split_once('@').ok_or_else(not_mysql)?;
            let (_, name) = rest.split_once('/').ok_or_else(not_mysql)?;
            let name = name.split('?').next().unwrap_or_default();
            Ok(format!("mysql://{user}@localhost/{name}?socket={socket}"))
        }
        Some(text) => Ok(text.to_owned()),
    }
}

/// Opens a DSN with Db::connect, runs SELECT 1 through the statement runner (INT-150), closes it and returns its driver:
/// the one implementation of dsn.connect (FCV-4). A refused DSN or a failed statement returns its error code and message.
async fn connect_driver(dsn: &str) -> Result<String, (String, String)> {
    match polyspec_orm::Db::connect(dsn, 1, polyspec_orm::Config::default()).await {
        Ok(db) => {
            let driver = db.driver().to_owned();
            let answer = db.utils().run(async |frame| frame.run("utility", &[], "SELECT 1", &[]).await).await;
            db.close().await;
            match answer {
                Ok(rows) if matches!(rows.as_slice(), [row] if matches!(row.as_slice(), [Val::I64(1)])) => Ok(driver),
                Ok(rows) => Err(("STEP".to_owned(), format!("SELECT 1 on the connection of {driver} returned {rows:?}"))),
                Err(error) => Err((error.code().to_owned(), error.to_string())),
            }
        }
        Err(error) => Err((error.code().to_owned(), error.to_string())),
    }
}

/// The dsn.connect op (FCV-4) on the DSN text of the step, checked against the outcome of the expect of `database`.
fn dsn_connect(step: &Value, database: &str) -> Result<(), String> {
    let expect = &step["expect"][database];
    let dsn = step["dsn"].as_str().unwrap_or_default();
    let runtime = tokio::runtime::Builder::new_current_thread().enable_all().build().map_err(|error| error.to_string())?;
    let outcome = runtime.block_on(connect_driver(dsn));
    match (outcome, expect["error"].as_str()) {
        (Err((got, _)), Some(code)) if got == code => Ok(()),
        (Err((got, message)), Some(code)) => Err(format!("error {got} ({message}), want {code}")),
        (Ok(_), Some(code)) => Err(format!("error none, want {code}")),
        (Err((_, message)), None) => Err(format!("unexpected error {message}")),
        (Ok(driver), None) => {
            if expect["value"] == serde_json::json!({ "text": driver }) {
                Ok(())
            } else {
                Err(format!("driver {driver}, want {}", expect["value"]))
            }
        }
    }
}

/// The rows that the canned catalog of a dbspec.introspect_shown vector answers to `query`.
fn shown_catalog_rows(catalog: &Value, name: &str, create: &str, query: &str) -> Result<Vec<Vec<dbspec::CatalogValue>>, String> {
    use dbspec::CatalogValue;
    let text = |value: &Value| CatalogValue::Text(value.as_str().unwrap_or_default().to_owned());
    let t = || text(&catalog["table"]);
    let s = |value: &str| CatalogValue::Text(value.to_owned());
    Ok(if query.contains("information_schema.TABLES") {
        vec![vec![t(), s("BASE TABLE"), s("")]]
    } else if query.contains("information_schema.COLUMNS") {
        let columns = catalog["columns"].as_array().ok_or("the catalog has no columns")?;
        columns
            .iter()
            .map(|c| vec![t(), text(&c["name"]), text(&c["type"]), text(&c["nullable"]), CatalogValue::Null, s(""), text(&c["charset"]), text(&c["collation"]), s("")])
            .collect()
    } else if query.contains("information_schema.STATISTICS") {
        vec![vec![t(), s("PRIMARY"), CatalogValue::Int(0), text(&catalog["primary_key"]), s("A"), CatalogValue::Int(0), CatalogValue::Int(0), s("BTREE")]]
    } else if query.contains("REFERENTIAL_CONSTRAINTS") {
        Vec::new()
    } else if query.contains("CHECK_CONSTRAINTS") {
        vec![vec![s(name), text(&catalog["stored_clause"])]]
    } else if query.contains("TABLE_CONSTRAINTS") {
        vec![vec![t(), s(name), s("YES")]]
    } else if query.contains("information_schema.TRIGGERS") || query.contains("information_schema.ROUTINES") || query.contains("information_schema.EVENTS") {
        Vec::new()
    } else if query.contains("SHOW CREATE TABLE") {
        vec![vec![t(), s(create)]]
    } else {
        return Err(format!("the canned catalog has no answer for the query {query:?}"));
    })
}

/// The dbspec.introspect_shown op (FCV-4): the public catalog queries and read_catalog on the canned catalog of a case of the
/// vectors file, whose check lines and unsupported objects, or error, it compares with the expect of `database` (DIA-84). A
/// reason compares by its rule, the text before the first ": ", since its text differs between the clients.
fn dbspec_introspect_shown(step: &Value, database: &str, dir: &Path) -> Result<(), String> {
    let path = dir.join(step["vectors"].as_str().unwrap_or_default());
    let vectors: Value = serde_json::from_str(&std::fs::read_to_string(&path).map_err(|error| format!("{}: {error}", path.display()))?).map_err(|error| error.to_string())?;
    let id = step["case"].as_str().unwrap_or_default();
    let cases = vectors["cases"].as_array().ok_or("the vectors have no cases")?;
    let case = cases.iter().find(|case| case["id"] == id).ok_or_else(|| format!("the vectors have no case {id}"))?;
    let lines: Vec<&str> = case["create"].as_array().ok_or("the case has no create")?.iter().filter_map(Value::as_str).collect();
    let create = format!("{}\n", lines.join("\n"));
    let name = case["name"].as_str().unwrap_or_default();
    let catalog = &vectors["catalog"];
    let mut results = Vec::new();
    for query in dbspec::catalog_queries(Dialect::MySql) {
        results.push(shown_catalog_rows(catalog, name, &create, query)?);
    }
    for query in dbspec::catalog_followups(Dialect::MySql, &results)? {
        results.push(shown_catalog_rows(catalog, name, &create, &query)?);
    }
    let read = dbspec::read_catalog(Dialect::MySql, &results, "introspected");
    let expect = &step["expect"][database];
    if let Some(want) = expect["error"].as_str() {
        return match read {
            Err(got) if got == want => Ok(()),
            Err(got) => Err(format!("error {got:?}, want {want:?}")),
            Ok(_) => Err(format!("read the catalog, want the error {want:?}")),
        };
    }
    let introspection = read?;
    let checks: Vec<String> = dbspec::emit(&introspection.document).lines().map(str::trim).filter(|line| line.starts_with("check ")).map(str::to_owned).collect();
    let unsupported: Vec<String> = introspection
        .unsupported
        .iter()
        .map(|item| format!("{} {}: {}", item.kind, item.name, item.reason.split_once(": ").map_or(item.reason.as_str(), |(rule, _)| rule)))
        .collect();
    if json!(checks) == expect["checks"] && json!(unsupported) == expect["unsupported"] {
        Ok(())
    } else {
        Err(format!("checks {checks:?} and unsupported {unsupported:?}, want {expect}"))
    }
}

/// The dbspec.introspect_sqlite op (FCV-4): the statements on a memory SQLite connection of its own, then the
/// public introspect, whose unsupported objects it compares with the expect of `database` (DIA-191).
fn dbspec_introspect_sqlite(step: &Value, database: &str) -> Result<(), String> {
    use sqlx::Connection;
    let runtime = tokio::runtime::Builder::new_current_thread().enable_all().build().map_err(|error| error.to_string())?;
    let unsupported = runtime.block_on(async {
        let mut connection = sqlx::SqliteConnection::connect("sqlite::memory:").await.map_err(|error| error.to_string())?;
        for statement in step["sql"].as_array().ok_or("sql is not a list")? {
            let text = statement.as_str().ok_or("a statement is not a string")?.to_owned();
            sqlx::query(sqlx::AssertSqlSafe(text)).execute(&mut connection).await.map_err(|error| error.to_string())?;
        }
        let introspection = dbspec::introspect(&mut connection, Dialect::Sqlite, "introspected").await.map_err(|error| error.to_string())?;
        connection.close().await.map_err(|error| error.to_string())?;
        Ok::<_, String>(introspection.unsupported)
    })?;
    let got: Vec<Value> = unsupported
        .iter()
        .map(|item| json!({ "kind": item.kind, "table": item.table, "name": item.name, "reason": item.reason }))
        .collect();
    let want = &step["expect"][database]["unsupported"];
    if want.as_array().map(Vec::as_slice) == Some(got.as_slice()) {
        Ok(())
    } else {
        Err(format!("unsupported objects {got:?}, want {want}"))
    }
}

/// The keyring.versions op (FCV-4): the public constructor of the keyring, then its current version and its versions (INT-74,
/// INT-130), against the expect of `database`.
fn keyring_versions(step: &Value, database: &str) -> Result<(), String> {
    let expect = &step["expect"][database];
    let versions = step["keyring"]["versions"].as_object().ok_or("the keyring has no versions")?;
    let mut keys = std::collections::BTreeMap::new();
    for (version, key) in versions {
        keys.insert(version.parse::<i32>().map_err(|error| error.to_string())?, key.as_str().ok_or("a key is not a text")?.to_owned());
    }
    let current = step["keyring"]["current"].as_i64().ok_or("the keyring has no current version")?;
    let current = i32::try_from(current).map_err(|error| error.to_string())?;
    match (polyspec_orm::AesKeyring::new(keys, current), expect["error"].as_str()) {
        (Err(error), Some(code)) if error.code() == code => Ok(()),
        (Err(error), _) => Err(format!("the keyring returned {error}, want {expect}")),
        (Ok(_), Some(code)) => Err(format!("the keyring was built, want {code}")),
        (Ok(keyring), None) => {
            let got = json!({ "current": keyring.current(), "versions": keyring.versions() });
            if &got == expect {
                Ok(())
            } else {
                Err(format!("keyring {got}, want {expect}"))
            }
        }
    }
}

/// The markdown.builder op (FCV-4): the builder calls on the slots model, then get_count, on the listener of markdown.send. The
/// terminal returns the first recorded error before it sends a message (INT-88, INT-89).
fn markdown_builder(step: &Value, database: &str) -> Result<(), String> {
    let calls: Vec<String> = step["calls"].as_array().ok_or("the step has no calls")?.iter().filter_map(|call| call.as_str().map(str::to_owned)).collect();
    let listener = markdown::send_listener();
    let result = call_on_connection(listener.dsn.clone(), Call::Builder(calls));
    if let Some(message) = listener.finish() {
        return Err(format!("the terminal sent {message} before its error"));
    }
    let expect = &step["expect"][database];
    let (code, contains) = (expect["error"].as_str().unwrap_or_default(), expect["message_contains"].as_str().unwrap_or_default());
    match result {
        Err(error) if error.code() == code && error.to_string().contains(contains) => Ok(()),
        Err(error) => Err(format!("the terminal returned {error}, want {code} with {contains}")),
        Ok(()) => Err(format!("the terminal returned no error, want {code}")),
    }
}

/// Maps the op of `step` to its call and checks the result against the expect of `database`.
fn run(step: &Value, bound: &mut HashMap<String, Outcome>, database: &str, dir: &Path) -> Result<(), String> {
    match step["op"].as_str().unwrap_or_default() {
        "dsn.connect" => return dsn_connect(step, database),
        "dbspec.introspect_shown" => return dbspec_introspect_shown(step, database, dir),
        "dbspec.introspect_sqlite" => return dbspec_introspect_sqlite(step, database),
        "keyring.versions" => return keyring_versions(step, database),
        "markdown.builder" => return markdown_builder(step, database),
        "planner.compile" => return planner_compile(step, database, dir),
        "generator.generate" => return recipe_generator::check(step, database, dir),
        "ir.validate" => return ir_validate(step, database),
        "dbspec.parse" | "dbspec.parse_plan" | "dbspec.emit_plan" | "dbspec.plan_steps" | "dbspec.diff" | "dbspec.chain" | "dbspec.compare" => {
            return dbspec_plan_step(step, bound, database)
        }
        "dbspec.parse_emit"
        | "dbspec.manifest"
        | "dbspec.render"
        | "dbspec.analyze"
        | "dbspec.parse_positions"
        | "dbspec.format"
        | "dbspec.parse_set"
        | "dbspec.set"
        | "dbspec.read_file"
        | "dbspec.read_bytes" => return dbspec_step(step, dir, database),
        "dbspec.export_mermaid" | "dbspec.import_mermaid" => return mermaid(step, bound, database, dir),
        _ => {}
    }
    if step["op"] == "ir.answer" {
        // The chain runs on a listener that answers with the step's answer (or answers), and its value is compared as JSON (FCV-3).
        // An expect of {params} compares the params of the request that the listener received instead (PRT-66, PRT-67).
        let expect = &step["expect"][database];
        let params = expect.get("params").is_some();
        if params && step["answers"].is_object() {
            return Err("a params expect needs one answer, not answers".to_owned());
        }
        let present = if params { expect.get("params") } else { expect.get("value") };
        let Some(want) = present else {
            return Err(format!("ir.answer expect for {database} has neither value nor params"));
        };
        let chain = step["chain"].as_str().unwrap_or_default();
        let got = markdown::answer(chain, &step["answer"], &step["answers"], params);
        return if markdown::same(&got, want) { Ok(()) } else { Err(format!("got {got}, want {want}")) };
    }
    if step["op"] == "markdown.send" {
        return markdown_send(step);
    }
    if step["op"] == "collection.key" {
        return collection_key(step, database);
    }
    if step["op"] == "model.assign" {
        return model_assign(step);
    }
    let styles: Vec<String> = step["styles"].as_array().map(|s| s.iter().filter_map(|x| x.as_str().map(str::to_owned)).collect()).unwrap_or_default();
    let key = step["key"].as_str().unwrap_or_default();
    let op = step["op"].as_str().unwrap_or_default();
    let failed = |error: polyspec_orm::Error| (error.code().to_owned(), error.to_string());
    let outcome: Outcome = match op {
        "codec.decode" => codec::decode(&styles, &cell(&step["raw"], bound)?).map(Produced::Read).map_err(failed),
        "codec.encode" => encode(&styles, &step["value"], bound)?.map(Produced::Written).map_err(failed),
        "codec.host_encode" => codec::host_encode(&param(&step["value"], bound)?, &styles, key).map(Produced::Written).map_err(failed),
        "codec.host_decode" => codec::host_decode(&cell(&step["raw"], bound)?, &styles, key).map(Produced::Read).map_err(failed),
        "codec.blind_index" => codec::blind_index(&param(&step["value"], bound)?, key).map(|text| Produced::Written(Param::Str(text))).map_err(failed),
        other => return Err(format!("OP_UNKNOWN {other}")),
    };
    if let Some(name) = step["as"].as_str() {
        bound.insert(name.to_owned(), outcome.clone());
    }
    let Some(expect) = step["expect"].get(database) else {
        return match outcome {
            Err((_, message)) => Err(format!("unexpected error {message}")),
            Ok(_) => Ok(()),
        };
    };
    if let Some(code) = expect["error"].as_str() {
        return match outcome {
            Err((got, _)) if got == code => Ok(()),
            Err((got, message)) => Err(format!("error {got} ({message}), want {code}")),
            Ok(_) => Err(format!("error none, want {code}")),
        };
    }
    let want = &expect["value"];
    match outcome {
        Err((_, message)) => Err(format!("unexpected error {message}")),
        Ok(Produced::Written(written)) => compare_cell(want, &written),
        Ok(Produced::Read(Val::Null)) if want.get("null").is_some() => Ok(()),
        Ok(Produced::Read(read)) if op == "codec.host_decode" => compare_cell(want, &read_param(read)),
        Ok(Produced::Read(read)) => {
            let ordered = styles.iter().any(|s| s == "ordered_json");
            let got = from_val(&read)?;
            if equal(&got, want, ordered) {
                Ok(())
            } else {
                Err(format!("decoded {got}, want {want}"))
            }
        }
        Ok(Produced::Document(_) | Produced::Plan(_) | Produced::Plain(_)) => Err("a dbspec value is no codec value".to_owned()),
    }
}

/// The JSON form of a statement of a plan, as the planner fixture writes it: its role, sql, bind slots and tables.
fn planner_statement(step: &polyspec_orm::plan::Step) -> Value {
    let slots: Vec<Value> = step
        .bind_slots
        .iter()
        .map(|slot| {
            if slot.from == "parent" {
                return serde_json::json!({"from": slot.from, "key_types": slot.key_types});
            }
            let mut out = serde_json::json!({"from": slot.from, "type": slot.col_type});
            if slot.from == "param" {
                out["param"] = serde_json::json!(slot.param);
            }
            // A datetime or time slot carries its fraction digits.
            if slot.col_type == "datetime" || slot.col_type == "time" {
                out["precision"] = serde_json::json!(slot.precision);
            }
            // A varchar param slot carries its length.
            if slot.from == "param" && slot.col_type == "varchar" {
                out["length"] = serde_json::json!(slot.length);
            }
            // An assignment slot of a non-null column says so.
            if slot.not_null {
                out["not_null"] = serde_json::json!(true);
            }
            out
        })
        .collect();
    serde_json::json!({"role": step.role, "sql": step.sql, "slots": slots, "tables": step.tables})
}

/// The planner.compile op (FCV-4): the step builds its request from its JSON with the manifest hash of its schema, compiles it for
/// each dialect, and checks the plans with the expect of `database`, or the error code that every dialect fails with.
fn planner_compile(step: &Value, database: &str, dir: &Path) -> Result<(), String> {
    let want = step["expect"].get(database).ok_or_else(|| format!("planner.compile has no expect for {database}"))?;
    let schema = step["schema"].as_str().unwrap_or_default();
    // The schema is named relative to the directory of the recipe, which is absolute, so the path is absolute too.
    let manifest = ir_request::schema(&dir.join(schema).to_string_lossy());
    let input = ir_request::request(&step["input"], &manifest.manifest_hash);
    if let Some(code) = want.get("error").and_then(Value::as_str) {
        for (name, dialect) in PLAN_DIALECTS {
            let got = engine::compile(&manifest, dialect, &input).err().map(|error| error.code().to_owned());
            if got.as_deref() != Some(code) {
                return Err(format!("{name}: error {got:?}, want {code}"));
            }
        }
        return Ok(());
    }
    for (name, dialect) in PLAN_DIALECTS {
        let plan = engine::compile(&manifest, dialect, &input).map_err(|error| format!("{name}: {error}"))?;
        let got = Value::Array(plan.steps.iter().map(planner_statement).collect());
        if got != want["value"][name] {
            return Err(format!("{name}:\n got {got}\nwant {}", want["value"][name]));
        }
    }
    Ok(())
}

/// The ir.validate op (FCV-4): the step builds its request from its JSON with the manifest hash of the bench schema, then validates
/// it. A request shape that the typed request refuses is IR_INVALID. The expect of `database` is {error: CODE}, or {value: {bool:
/// true}} for an accepted request.
fn ir_validate(step: &Value, database: &str) -> Result<(), String> {
    let want = step["expect"].get(database).ok_or_else(|| format!("ir.validate has no expect for {database}"))?;
    if step["request"].get("manifest_hash").is_some() {
        return Err("the request already holds manifest_hash".to_owned());
    }
    let manifest = ir_request::schema(IR_VALIDATE_SCHEMA);
    let built = std::panic::catch_unwind(|| ir_request::request(&step["request"], &manifest.manifest_hash));
    let got: Result<(), String> = match built {
        Ok(request) => engine::validate(&manifest, &request).map_err(|error| error.code().to_owned()),
        Err(payload) => {
            let message = payload.downcast_ref::<String>().cloned().unwrap_or_default();
            match message.strip_prefix(ir_request::REJECTED) {
                Some(_) => Err("IR_INVALID".to_owned()),
                None => std::panic::resume_unwind(payload),
            }
        }
    };
    match want.get("error").and_then(Value::as_str) {
        Some(code) if got.as_ref().err().is_some_and(|c| c == code) => Ok(()),
        Some(code) => Err(format!("got {got:?}, want {code}")),
        None if want["value"] != serde_json::json!({"bool": true}) => Err(format!("ir.validate expects {{bool true}} or an error, not {}", want["value"])),
        None if got.is_ok() => Ok(()),
        None => Err(format!("got {got:?}, want valid")),
    }
}

/// The value that the ref of `raw` binds by an earlier step.
fn bound_value<'a>(raw: &Value, bound: &'a HashMap<String, Outcome>) -> Result<&'a Produced, String> {
    let name = raw["ref"].as_str().ok_or_else(|| format!("{raw} is not a ref"))?;
    match bound.get(name) {
        Some(Ok(value)) => Ok(value),
        _ => Err(format!("ref {name} binds no value")),
    }
}

/// The document that the ref of `raw` binds.
fn bound_document(raw: &Value, bound: &HashMap<String, Outcome>) -> Result<Document, String> {
    match bound_value(raw, bound)? {
        Produced::Document(document) => Ok(document.clone()),
        _ => Err(format!("ref {raw} binds no document")),
    }
}

/// The plan that the ref of `raw` binds.
fn bound_plan(raw: &Value, bound: &HashMap<String, Outcome>) -> Result<dbspec::Plan, String> {
    match bound_value(raw, bound)? {
        Produced::Plan(plan) => Ok(plan.clone()),
        _ => Err(format!("ref {raw} binds no plan")),
    }
}

/// The document of the key of a step, or none when the step has no such key or its value is null.
fn optional_document(step: &Value, key: &str, bound: &HashMap<String, Outcome>) -> Result<Option<Document>, String> {
    match step.get(key).filter(|raw| !raw.is_null()) {
        Some(raw) => bound_document(raw, bound).map(Some),
        None => Ok(None),
    }
}

/// The text of the lines of a step, each ended by LF (the lines joined by LF, then one LF).
fn plan_text(lines: &Value) -> String {
    let lines: Vec<&str> = lines.as_array().expect("lines").iter().map(|line| line.as_str().expect("line")).collect();
    format!("{}\n", lines.join("\n"))
}

/// The diagnostics as [rule, line, column, message]; the message is kept for rule plan, or for every rule when `every`.
fn plan_rows(diagnostics: &[dbspec::Diagnostic], every: bool) -> Value {
    Value::Array(
        diagnostics
            .iter()
            .map(|d| {
                let message = if every || d.rule == "plan" { Value::from(d.message.clone()) } else { Value::Null };
                serde_json::json!([d.rule, d.line, d.column, message])
            })
            .collect(),
    )
}

/// The messages of the diagnostics, each of rule `rule`.
fn plan_messages(diagnostics: &[dbspec::Diagnostic], rule: &str) -> Result<Value, String> {
    let mut messages = Vec::with_capacity(diagnostics.len());
    for d in diagnostics {
        if d.rule != rule {
            return Err(format!("diagnostic of rule {}, want {rule}: {}", d.rule, d.message));
        }
        messages.push(Value::from(d.message.clone()));
    }
    Ok(Value::Array(messages))
}

/// The object of a plan step (docs/spec/plans.md "Steps"): its statement, its effect as text, and the fields that the step has.
fn plan_fields(s: &dbspec::PlanStep) -> Value {
    let mut out = Map::new();
    out.insert("statement".into(), Value::from(s.statement.clone()));
    out.insert("effect".into(), Value::from(s.effect.to_string()));
    if !s.rollback.is_empty() {
        out.insert("rollback".into(), Value::from(s.rollback.clone()));
    } else if !s.irreversible.is_empty() {
        out.insert("irreversible".into(), Value::from(s.irreversible.clone()));
    }
    if !s.restore.is_empty() {
        out.insert("restore".into(), Value::from(s.restore.clone()));
    }
    if !s.rollback_restore.is_empty() {
        out.insert("rollback_restore".into(), Value::from(s.rollback_restore.clone()));
    }
    if let Some(e) = s.restore_if.as_ref().filter(|_| !s.restore.is_empty() || !s.rollback_restore.is_empty()) {
        out.insert("restore_if".into(), Value::from(e.to_string()));
    }
    if !s.null_checks.is_empty() {
        let checks = s
            .null_checks
            .iter()
            .map(|c| Value::Array(vec![c.table.clone().into(), c.column.clone().into(), c.default.clone().map_or(Value::Null, Value::from)]))
            .collect();
        out.insert("null_checks".into(), Value::Array(checks));
    }
    if s.finalize {
        out.insert("finalize".into(), Value::Bool(true));
    }
    Value::Object(out)
}

/// The dialect that a name gives (mysql, postgres or sqlite) for a dbspec plan op.
fn plan_dialect(name: &str) -> Result<Dialect, String> {
    match name {
        "mysql" => Ok(Dialect::MySql),
        "postgres" => Ok(Dialect::Postgres),
        "sqlite" => Ok(Dialect::Sqlite),
        other => Err(format!("dialect {other} is not mysql, postgres or sqlite")),
    }
}

/// The dbspec plan ops of a recipe step (FCV-4), each through its public dbspec call: parse, parse_plan, emit_plan, plan_steps,
/// diff, chain and compare. A document or a plan that a step binds with `as` is the value of the ref of a later step. The result
/// of the step is compared, as JSON, with the expect of `database`.
fn dbspec_plan_step(step: &Value, bound: &mut HashMap<String, Outcome>, database: &str) -> Result<(), String> {
    let op = step["op"].as_str().unwrap_or_default();
    let want = step["expect"].get(database).ok_or_else(|| format!("{op} has no expect for {database}"))?;
    let binds = step["as"].as_str().map(str::to_owned);
    let got = match op {
        "dbspec.parse" => match dbspec::parse(&plan_text(&step["lines"]), &BTreeMap::new()) {
            Ok(parsed) => {
                if let Some(name) = binds {
                    bound.insert(name, Ok(Produced::Document(parsed.document)));
                }
                serde_json::json!({"diagnostics": []})
            }
            Err(diagnostics) => serde_json::json!({"diagnostics": plan_rows(&diagnostics, false)}),
        },
        "dbspec.parse_plan" => match dbspec::parse_plan(&plan_text(&step["lines"])) {
            Ok(parsed) => {
                if let Some(name) = binds {
                    bound.insert(name, Ok(Produced::Plan(parsed)));
                }
                serde_json::json!({"diagnostics": []})
            }
            Err(diagnostics) => serde_json::json!({"diagnostics": plan_rows(&diagnostics, false)}),
        },
        "dbspec.emit_plan" => serde_json::json!({"text": dbspec::emit_plan(&bound_plan(&step["plan"], bound)?)}),
        "dbspec.plan_steps" => {
            let source = optional_document(step, "source", bound)?;
            let plan = bound_plan(&step["plan"], bound)?;
            let dialect = plan_dialect(step["dialect"].as_str().unwrap_or_default())?;
            match dbspec::plan_steps(source.as_ref(), &plan, dialect) {
                Ok(steps) => serde_json::json!({"steps": steps.iter().map(plan_fields).collect::<Vec<Value>>()}),
                Err(diagnostics) => serde_json::json!({"messages": plan_messages(&diagnostics, "plan")?}),
            }
        }
        "dbspec.diff" => {
            let source = optional_document(step, "source", bound)?;
            let plan = bound_plan(&step["plan"], bound)?;
            match dbspec::diff(source.as_ref(), &plan) {
                Ok(changes) => serde_json::json!({"changes": changes.iter().map(|c| serde_json::json!([c.kind, c.table, c.name])).collect::<Vec<Value>>()}),
                Err(diagnostics) => serde_json::json!({"messages": plan_messages(&diagnostics, "plan")?}),
            }
        }
        "dbspec.chain" => {
            let raw = step["plans"].as_array().ok_or_else(|| "dbspec.chain has no plans".to_owned())?;
            let plans = raw.iter().map(|raw| bound_plan(raw, bound)).collect::<Result<Vec<dbspec::Plan>, String>>()?;
            match dbspec::chain(&plans) {
                Ok(ordered) => serde_json::json!({"order": ordered.iter().map(|p| p.name()).collect::<Vec<&str>>()}),
                Err(diagnostics) => serde_json::json!({"messages": plan_messages(&diagnostics, "chain")?}),
            }
        }
        "dbspec.compare" => {
            let source = bound_document(&step["source"], bound)?;
            let target = bound_document(&step["target"], bound)?;
            match dbspec::compare_schemas(&source, &target) {
                Ok(differences) => serde_json::json!({
                    "differences": differences.iter().map(|d| serde_json::json!([d.kind, d.table, d.name])).collect::<Vec<Value>>(),
                    "diagnostics": [],
                }),
                Err(diagnostics) => serde_json::json!({"differences": [], "diagnostics": plan_rows(&diagnostics, true)}),
            }
        }
        other => return Err(format!("OP_UNKNOWN {other}")),
    };
    if got == *want {
        Ok(())
    } else {
        Err(format!("got {got}, want {want}"))
    }
}

/// The documents of a dbspec step, read from `dir` and parsed with the set of their headers (FCV-4). A document without a
/// `dbspec <kind> <name>` header is refused, as the reference implementation does.
fn read_documents(dir: &Path, paths: &[String]) -> Result<(Vec<String>, Vec<Document>), String> {
    let mut texts = Vec::with_capacity(paths.len());
    let mut set = BTreeMap::new();
    for path in paths {
        let text = std::fs::read_to_string(dir.join(path)).map_err(|error| format!("{path}: {error}"))?;
        let header: Vec<&str> = text.split('\n').next().unwrap_or_default().split_whitespace().collect();
        match header.as_slice() {
            ["dbspec", _, name] => set.insert((*name).to_owned(), text.clone()),
            _ => return Err(format!("{path} has no dbspec header")),
        };
        texts.push(text);
    }
    let mut documents = Vec::with_capacity(texts.len());
    for (path, text) in paths.iter().zip(&texts) {
        let parsed = dbspec::parse(text, &set).map_err(|errors| format!("{path}: {errors:?}"))?;
        documents.push(parsed.document);
    }
    Ok((texts, documents))
}

/// The documents named by a dbspec step.
fn step_documents(step: &Value) -> Vec<String> {
    step["documents"].as_array().map(|d| d.iter().filter_map(|x| x.as_str().map(str::to_owned)).collect()).unwrap_or_default()
}

/// Runs a dbspec.export_mermaid or dbspec.import_mermaid op (FCV-4) on the public Mermaid calls (DBS-169), binds its plain JSON
/// result to `as`, and checks the keys that the expect value of `database` names, as a subset.
fn mermaid(step: &Value, bound: &mut HashMap<String, Outcome>, database: &str, dir: &Path) -> Result<(), String> {
    let op = step["op"].as_str().unwrap_or_default();
    let want = &step["expect"][database]["value"];
    let got = if op == "dbspec.export_mermaid" { mermaid_export(step, dir)? } else { mermaid_import(step, bound, dir)? };
    if let Some(name) = step["as"].as_str() {
        bound.insert(name.to_owned(), Ok(Produced::Plain(got.clone())));
    }
    let Some(subset) = want.as_object() else { return Err(format!("{op} has no expect value for {database}: {want}")) };
    for (key, value) in subset {
        match got.get(key) {
            Some(actual) if actual == value => {}
            Some(actual) => return Err(format!("{key}: got {actual}, want {value}")),
            None => return Err(format!("the result has no {key}: {got}")),
        }
    }
    Ok(())
}

/// The export op: the Mermaid text and the dropped objects of the inline text with the other documents of its set, or of
/// the .dbs file `document`.
fn mermaid_export(step: &Value, dir: &Path) -> Result<Value, String> {
    let (source, set) = match step["document"].as_str() {
        Some(path) => (mermaid_file(dir, path)?, BTreeMap::new()),
        None => inline_text(step),
    };
    let document = mermaid_document(&source, &set)?;
    let (text, dropped) = export_mermaid(&document);
    Ok(json!({"mermaid": text, "dropped": drops(&dropped)}))
}

/// The import op: the document and the dropped objects of a Mermaid text, or its errors; with `skeleton_of`, whether the
/// tables, columns, primary keys and foreign keys equal those of the file (MER-13).
fn mermaid_import(step: &Value, bound: &HashMap<String, Outcome>, dir: &Path) -> Result<Value, String> {
    let text = mermaid_text(&step["mermaid"], bound)?;
    let name = step["name"].as_str().unwrap_or_default();
    let (document, dropped) = match import_mermaid(&text, name) {
        Ok(imported) => imported,
        Err(diagnostics) => {
            let errors: Vec<Value> = diagnostics.iter().map(|d| json!([d.rule, d.line, d.column])).collect();
            return Ok(json!({"errors": errors}));
        }
    };
    let Some(skeleton_of) = step["skeleton_of"].as_str() else {
        return Ok(json!({"document": dbspec::emit(&document), "dropped": drops(&dropped)}));
    };
    let original = mermaid_document(&mermaid_file(dir, skeleton_of)?, &BTreeMap::new())?;
    Ok(json!({"dropped": drops(&dropped), "same_skeleton": mermaid_skeleton(&original) == mermaid_skeleton(&document)}))
}

/// The text of a .dbs file that a Mermaid op names, relative to the recipe file.
fn mermaid_file(dir: &Path, path: &str) -> Result<String, String> {
    dbspec::read_file(&dir.join(path)).map_err(|e| format!("{path}: {e}"))
}

fn mermaid_document(text: &str, set: &BTreeMap<String, String>) -> Result<Document, String> {
    dbspec::parse(text, set).map(|parsed| parsed.document).map_err(|e| format!("document: {e:?}"))
}

/// The Mermaid text of an import: a text, or a dotted ref to a field of a Mermaid result, such as {"ref": "e.mermaid"}.
fn mermaid_text(raw: &Value, bound: &HashMap<String, Outcome>) -> Result<String, String> {
    if let Some(text) = raw.as_str() {
        return Ok(text.to_owned());
    }
    let Some(name) = raw["ref"].as_str() else { return Err(format!("mermaid is a text or a ref: {raw}")) };
    let Some((result, field)) = name.split_once('.') else { return Err(format!("ref {name} names no field")) };
    match reference(result, bound)? {
        Produced::Plain(value) => value[field].as_str().map(str::to_owned).ok_or_else(|| format!("ref {name} names no text")),
        _ => Err(format!("ref {name} names no Mermaid result")),
    }
}

/// The `[kind, table, name]` list of the dropped objects.
fn drops(dropped: &[Unsupported]) -> Value {
    Value::Array(dropped.iter().map(|u| json!([u.kind, u.table, u.name])).collect())
}

/// The text of the one document of a dbspec step, read from `dir`.
fn step_document(step: &Value, dir: &Path) -> Result<String, String> {
    let path = step["document"].as_str().unwrap_or_default();
    std::fs::read_to_string(dir.join(path)).map_err(|error| format!("{path}: {error}"))
}

/// The JSON form of declaration positions, as the fixtures write them.
fn positions_json(positions: &[Position]) -> Vec<Value> {
    positions.iter().map(|p| serde_json::json!({"kind": p.kind, "path": p.path, "line": p.line, "column": p.column})).collect()
}

/// One dbspec op of a recipe step, through the public dbspec calls of polyspec_orm, checked against the expect of `database`.
/// The ops and their expects are those of docs/spec/feature-coverage.md FCV-4, and each one mirrors the reference
/// implementation (packages/go/internal/recipe/dbspec.go).
fn dbspec_step(step: &Value, dir: &Path, database: &str) -> Result<(), String> {
    let op = step["op"].as_str().unwrap_or_default();
    let Some(want) = step["expect"].get(database) else { return Err(format!("{op} has no expect for {database}")) };
    match op {
        "dbspec.parse_emit" => {
            let want_identical = want["identical"].as_bool().ok_or("expect identical is not a bool")?;
            let (texts, documents) = read_documents(dir, &step_documents(step))?;
            let identical = texts.iter().zip(&documents).all(|(text, document)| dbspec::emit(document) == *text);
            if identical == want_identical {
                Ok(())
            } else {
                Err(format!("emit identical = {identical}, want {want_identical}"))
            }
        }
        "dbspec.manifest" => {
            let want_hash = want["manifest_hash"].as_str().unwrap_or_default();
            let (_, documents) = read_documents(dir, &step_documents(step))?;
            let references: Vec<&Document> = documents.iter().collect();
            let manifest = dbspec::manifest(&references).map_err(|errors| format!("{errors:?}"))?;
            if want_hash.is_empty() || manifest.manifest_hash != want_hash {
                return Err(format!("manifest hash = {}, want {want_hash}", manifest.manifest_hash));
            }
            Ok(())
        }
        "dbspec.render" => {
            let (_, documents) = read_documents(dir, &step_documents(step))?;
            let references: Vec<&Document> = documents.iter().collect();
            for (name, dialect) in [("mysql", Dialect::MySql), ("postgres", Dialect::Postgres), ("sqlite", Dialect::Sqlite)] {
                let want_statements: Vec<String> =
                    want[name].as_array().map(|s| s.iter().filter_map(|x| x.as_str().map(str::to_owned)).collect()).unwrap_or_default();
                let got = dbspec::render(&references, dialect).map_err(|errors| format!("{name}: {errors:?}"))?;
                if want_statements.is_empty() || got != want_statements {
                    return Err(format!("{name} statements:\n got {got:?}\nwant {want_statements:?}"));
                }
            }
            Ok(())
        }
        "dbspec.analyze" => {
            // An empty token list is a result (a text that stops at a limit has none), so the expect must state the list.
            let want_tokens = want["tokens"].as_array().cloned().ok_or("dbspec.analyze has no tokens expect")?;
            let (text, set) = step_source(step, dir)?;
            let analysis = dbspec::analyze(&text, &set);
            // The analysis carries the parse result unchanged: its document, positions and diagnostics are those of the parse,
            // which is refused for an invalid text, so the analysis of that text gives its diagnostics.
            let (parsed_document, parsed_positions, parsed_diagnostics) = match dbspec::parse(&text, &set) {
                Ok(parsed) => (Some(dbspec::emit(&parsed.document)), Some(positions_json(&parsed.positions)), Vec::new()),
                Err(errors) => (None, None, errors),
            };
            let analysis_document = analysis.document.as_ref().map(dbspec::emit);
            let analysis_positions = analysis.positions.as_deref().map(positions_json);
            if analysis_document != parsed_document
                || analysis_positions != parsed_positions
                || diagnostic_values(&analysis.diagnostics) != diagnostic_values(&parsed_diagnostics)
            {
                return Err(format!("the analysis differs from the parse: {:?}", analysis.diagnostics));
            }
            let got: Vec<Value> = analysis.tokens.iter().map(|t| serde_json::json!([t.line, t.start, t.end, t.class])).collect();
            if got != want_tokens {
                return Err(format!("tokens:\n got {got:?}\nwant {want_tokens:?}"));
            }
            Ok(())
        }
        "dbspec.parse_positions" => {
            let want_positions = want["positions"].as_array().cloned().ok_or("dbspec.parse_positions has no positions expect")?;
            let (text, set) = step_source(step, dir)?;
            let parsed = dbspec::parse(&text, &set).map_err(|errors| format!("{errors:?}"))?;
            let got = positions_json(&parsed.positions);
            if got != want_positions {
                return Err(format!("positions:\n got {got:?}\nwant {want_positions:?}"));
            }
            Ok(())
        }
        "dbspec.format" => dbspec_format(step, want),
        "dbspec.parse_set" => dbspec_parse_set(step, want),
        "dbspec.set" => dbspec_set(step, want),
        "dbspec.read_file" | "dbspec.read_bytes" => dbspec_read(step, dir, want),
        other => Err(format!("OP_UNKNOWN {other}")),
    }
}

/// The lines of a JSON array of strings.
fn lines_of(value: &Value) -> Vec<&str> {
    value.as_array().map(|lines| lines.iter().filter_map(Value::as_str).collect()).unwrap_or_default()
}

/// The strings of a JSON array.
fn strings_of(value: &Value) -> Vec<String> {
    value.as_array().map(|items| items.iter().filter_map(|x| x.as_str().map(str::to_owned)).collect()).unwrap_or_default()
}

/// The lines joined with the line ends of a case: LF, CRLF when `crlf`, or alternating CRLF and LF with no line end on the
/// last line when `mixed`. This is the spelling of `join` in scripts/dbspec/syntax-vectors.mts.
fn joined_lines(lines: &[&str], crlf: bool, mixed: bool) -> String {
    let mut text = String::new();
    for (index, line) in lines.iter().enumerate() {
        text.push_str(line);
        if mixed {
            if index + 1 < lines.len() {
                text.push_str(if index % 2 == 0 { "\r\n" } else { "\n" });
            }
        } else {
            text.push_str(if crlf { "\r\n" } else { "\n" });
        }
    }
    text
}

/// The text of a step and the set of its other documents, each joined with the line ends of the step.
fn inline_text(step: &Value) -> (String, BTreeMap<String, String>) {
    let crlf = step["crlf"].as_bool() == Some(true);
    let mixed = step["mixed"].as_bool() == Some(true);
    let mut set = BTreeMap::new();
    if let Some(documents) = step["set"].as_object() {
        for (name, lines) in documents {
            set.insert(name.clone(), joined_lines(&lines_of(lines), crlf, mixed));
        }
    }
    let lines = expanded_lines(&step["text"]);
    (joined_lines(&lines.iter().map(String::as_str).collect::<Vec<_>>(), crlf, mixed), set)
}

/// The lines of a text (FCV-4): a repeat gives its lines count times with {var} replaced, a fill one line of its text.
fn expanded_lines(items: &Value) -> Vec<String> {
    let mut out = Vec::new();
    for item in items.as_array().into_iter().flatten() {
        if let Some(line) = item.as_str() {
            out.push(line.to_owned());
        } else if let Some(fill) = item.get("fill") {
            out.push(fill["text"].as_str().unwrap_or_default().repeat(fill["count"].as_u64().unwrap_or(0) as usize));
        } else {
            let repeat = &item["repeat"];
            let inner = expanded_lines(&repeat["lines"]);
            let mark = format!("{{{}}}", repeat["var"].as_str().unwrap_or_default());
            let from = repeat["from"].as_i64().unwrap_or(0);
            for i in from..from + repeat["count"].as_i64().unwrap_or(0) {
                let text = i.to_string();
                out.extend(inner.iter().map(|line| line.replace(&mark, &text)));
            }
        }
    }
    out
}

/// The text and the set of a dbspec step: inline when the step has text, else the document file of the step.
fn step_source(step: &Value, dir: &Path) -> Result<(String, BTreeMap<String, String>), String> {
    if step["text"].is_array() {
        return Ok(inline_text(step));
    }
    Ok((step_document(step, dir)?, BTreeMap::new()))
}

/// Parses the text with the set, emits it, and checks that the emission parses and emits to itself. The emission is the result.
fn emit_stable(text: &str, set: &BTreeMap<String, String>) -> Result<String, String> {
    let parsed = dbspec::parse(text, set).map_err(|errors| format!("the text is refused: {errors:?}"))?;
    let first = dbspec::emit(&parsed.document);
    let again = dbspec::parse(&first, set).map_err(|errors| format!("the emission is refused: {errors:?}"))?;
    if dbspec::emit(&again.document) != first {
        return Err("the emission is not idempotent".to_owned());
    }
    Ok(first)
}

/// The diagnostics as the expect writes them: the rule, line and column of each.
fn diagnostic_values(diagnostics: &[dbspec::Diagnostic]) -> Vec<Value> {
    diagnostics.iter().map(|d| serde_json::json!({"rule": d.rule, "line": d.line, "column": d.column})).collect()
}

/// A refused text: parse and format both refuse it with the expect's diagnostics, each with a message, and no document or text.
fn check_refusal(text: &str, set: &BTreeMap<String, String>, want: &[Value]) -> Result<(), String> {
    let parse_errors = match dbspec::parse(text, set) {
        Ok(_) => return Err("a document with a diagnostic parsed".to_owned()),
        Err(errors) => errors,
    };
    let format_errors = match dbspec::format(text, set) {
        Ok(rewritten) => return Err(format!("a document with a diagnostic was rewritten:\n{rewritten}")),
        Err(errors) => errors,
    };
    for errors in [&parse_errors, &format_errors] {
        let got = diagnostic_values(errors);
        if got.is_empty() || got != want {
            return Err(format!("diagnostics = {got:?}, want {want:?}"));
        }
        if errors.iter().any(|e| e.message.is_empty()) {
            return Err("a diagnostic has no message".to_owned());
        }
    }
    Ok(())
}

/// The dbspec.format op: the text of the step formats to the expect's text, and the emission of the text is that text too,
/// and the formatted text formats to itself; or the text is refused with the expect's diagnostics.
fn dbspec_format(step: &Value, want: &Value) -> Result<(), String> {
    if expanded_lines(&step["text"]).is_empty() {
        return Err("dbspec.format has no text".to_owned());
    }
    let (text, set) = inline_text(step);
    if let Some(want_diagnostics) = want["diagnostics"].as_array() {
        return check_refusal(&text, &set, want_diagnostics);
    }
    let want_lines = expanded_lines(&want["text"]);
    let expected = joined_lines(&want_lines.iter().map(String::as_str).collect::<Vec<_>>(), false, false);
    let emitted = emit_stable(&text, &set)?;
    if emitted != expected {
        return Err(format!("emission:\n{emitted}\nwant\n{expected}"));
    }
    let formatted = dbspec::format(&text, &set).map_err(|diagnostics| format!("{diagnostics:?}"))?;
    if formatted != expected {
        return Err(format!("formatted text:\n{formatted}\nwant\n{expected}"));
    }
    match dbspec::format(&formatted, &set) {
        Ok(again) if again == formatted => Ok(()),
        Ok(again) => Err(format!("the format of the formatted text differs:\n{again}")),
        Err(diagnostics) => Err(format!("the formatted text is refused: {diagnostics:?}")),
    }
}

/// The name of a document: the third word of its header line.
fn header_name(text: &str) -> String {
    text.split('\n').next().unwrap_or_default().split_whitespace().nth(2).unwrap_or_default().to_owned()
}

/// The document texts of a manifest or external text: each starts at a line that begins with `dbspec `.
fn split_documents(text: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for line in text.split_inclusive('\n') {
        if out.is_empty() || line.starts_with("dbspec ") {
            out.push(String::new());
        }
        out.last_mut().expect("a document").push_str(line);
    }
    out
}

/// The table names that the CREATE TABLE statements create, in statement order.
fn created_tables(statements: &[String]) -> Vec<String> {
    statements
        .iter()
        .filter_map(|s| s.strip_prefix("CREATE TABLE "))
        .map(|rest| rest.split(' ').next().unwrap_or_default().trim_matches(|c| c == '`' || c == '"').to_owned())
        .collect()
}

/// Checks that the errors have the rule, line and column of each expected diagnostic, in order, each with a message.
fn same_diagnostics(want: &[Value], got: &[dbspec::Diagnostic]) -> Result<(), String> {
    let values = diagnostic_values(got);
    if values != want {
        return Err(format!("diagnostics = {values:?}, want {want:?}"));
    }
    if got.iter().any(|e| e.message.is_empty()) {
        return Err("a diagnostic has no message".to_owned());
    }
    Ok(())
}

/// The dbspec.set op (the port of checkSet of packages/go/internal/recipe/dbspec.go). The owned texts, then the external
/// texts, are parsed each against the other texts and the parsing texts, and dbspec::manifest builds the set's manifest.
/// A refused set (expect diagnostics not empty) expects those diagnostics from the manifest and from each dialect of render,
/// and no manifest and no statements. A built set expects its texts and hashes when expect.manifest is given, parses its
/// manifest and external texts back as a set without diagnostics, gives the same hashes in the reversed order, and renders
/// statements in each dialect that create the tables of expect.created.
fn dbspec_set(step: &Value, want: &Value) -> Result<(), String> {
    let owned = strings_of(&step["owned"]);
    let external = strings_of(&step["external"]);
    let parsing: BTreeMap<String, String> = step["parsing"]
        .as_object()
        .map(|map| map.iter().map(|(name, text)| (name.clone(), text.as_str().unwrap_or_default().to_owned())).collect())
        .unwrap_or_default();
    let all: Vec<String> = owned.iter().chain(external.iter()).cloned().collect();
    let mut documents = Vec::with_capacity(all.len());
    for (i, text) in all.iter().enumerate() {
        let mut set = parsing.clone();
        for (j, other) in all.iter().enumerate() {
            if j != i {
                set.insert(header_name(other), other.clone());
            }
        }
        let parsed = dbspec::parse(text, &set).map_err(|errors| format!("document {}: {errors:?}", i + 1))?;
        let mut document = parsed.document;
        document.external = i >= owned.len();
        documents.push(document);
    }
    let references: Vec<&Document> = documents.iter().collect();
    let want_diagnostics: Vec<Value> = want["diagnostics"].as_array().cloned().unwrap_or_default();
    let refused = !want_diagnostics.is_empty();
    let built = dbspec::manifest(&references);
    match &built {
        Err(errors) => same_diagnostics(&want_diagnostics, errors)?,
        Ok(_) if refused => return Err("the set has no diagnostics, want the expected ones".to_owned()),
        Ok(_) => {}
    }
    for (name, dialect) in [("mysql", Dialect::MySql), ("postgres", Dialect::Postgres), ("sqlite", Dialect::Sqlite)] {
        let rendered = dbspec::render(&references, dialect);
        if refused {
            match rendered {
                Err(errors) => same_diagnostics(&want_diagnostics, &errors).map_err(|e| format!("render {name}: {e}"))?,
                Ok(_) => return Err(format!("render {name}: statements for a refused set")),
            }
            continue;
        }
        let statements = rendered.map_err(|errors| format!("render {name}: {errors:?}"))?;
        if statements.is_empty() {
            return Err(format!("render {name}: no statements"));
        }
        if let Some(created) = want["created"].as_array() {
            let want_created: Vec<String> = created.iter().filter_map(|x| x.as_str().map(str::to_owned)).collect();
            if created_tables(&statements) != want_created {
                return Err(format!("tables that {name} creates: {:?}, want {want_created:?}", created_tables(&statements)));
            }
        }
    }
    if refused {
        return Ok(());
    }
    let manifest = built.map_err(|errors| format!("{errors:?}"))?;
    let want_manifest = &want["manifest"];
    if !want_manifest.is_null() {
        let field = |key: &str| want_manifest[key].as_str().unwrap_or_default();
        for (key, got, want) in [
            ("manifest_text", manifest.manifest_text.as_str(), field("manifest_text")),
            ("schema_text", manifest.schema_text.as_str(), field("schema_text")),
            ("manifest_hash", manifest.manifest_hash.as_str(), field("manifest_hash")),
            ("schema_hash", manifest.schema_hash.as_str(), field("schema_hash")),
        ] {
            if got != want {
                return Err(format!("{key}:\n{got}\nwant\n{want}"));
            }
        }
        if let Some(text) = want_manifest["external_text"].as_str() {
            if manifest.external_text != text {
                return Err(format!("external_text:\n{}\nwant\n{text}", manifest.external_text));
            }
        }
    }
    // The manifest and external text parse back as a set without diagnostics (docs/spec/dbspec.md "Manifest and hashes").
    let owned_texts = split_documents(&manifest.manifest_text);
    let external_texts = split_documents(&manifest.external_text);
    let owned_refs: Vec<&str> = owned_texts.iter().map(String::as_str).collect();
    let external_refs: Vec<&str> = external_texts.iter().map(String::as_str).collect();
    for r in dbspec::parse_set(&owned_refs, &external_refs) {
        if !r.diagnostics.is_empty() {
            return Err(format!("manifest and external text of {:?}: {:?}", r.name, r.diagnostics));
        }
    }
    let reversed: Vec<&Document> = references.iter().rev().copied().collect();
    let again = dbspec::manifest(&reversed).map_err(|errors| format!("the reversed set: {errors:?}"))?;
    if again.manifest_hash != manifest.manifest_hash || again.schema_hash != manifest.schema_hash {
        return Err("the manifest of the reversed set differs".to_owned());
    }
    Ok(())
}

/// The dbspec.parse_set op: the owned and external texts parse as one set, and each result has the expect's name, external
/// mark, parsed flag and diagnostics (with its message where the expect states one).
fn dbspec_parse_set(step: &Value, want: &Value) -> Result<(), String> {
    let owned = strings_of(&step["owned"]);
    let external = strings_of(&step["external"]);
    let owned: Vec<&str> = owned.iter().map(String::as_str).collect();
    let external: Vec<&str> = external.iter().map(String::as_str).collect();
    let got = dbspec::parse_set(&owned, &external);
    let want_documents = want["documents"].as_array().cloned().unwrap_or_default();
    if got.len() != want_documents.len() {
        return Err(format!("{} results, want {}", got.len(), want_documents.len()));
    }
    for (index, (g, w)) in got.iter().zip(&want_documents).enumerate() {
        let name = g.name.clone().unwrap_or_default();
        let want_external = w["external"].as_bool() == Some(true);
        let want_parsed = w["parsed"].as_bool() == Some(true);
        if name != w["name"].as_str().unwrap_or_default() || g.external != want_external || g.document.is_some() != want_parsed {
            return Err(format!("document {index}: name {name:?}, external {}, parsed {}", g.external, g.document.is_some()));
        }
        let want_diagnostics = w["diagnostics"].as_array().cloned().unwrap_or_default();
        if g.diagnostics.len() != want_diagnostics.len() {
            return Err(format!("document {index}: diagnostics {:?}, want {want_diagnostics:?}", g.diagnostics));
        }
        for (k, (d, x)) in g.diagnostics.iter().zip(&want_diagnostics).enumerate() {
            let same = d.rule == x["rule"].as_str().unwrap_or_default()
                && d.line as u64 == x["line"].as_u64().unwrap_or(u64::MAX)
                && d.column as u64 == x["column"].as_u64().unwrap_or(u64::MAX);
            let same_message = x.get("message").is_none_or(|m| d.message == m.as_str().unwrap_or_default());
            if !same || !same_message {
                return Err(format!("document {index} diagnostic {k}: {d:?}, want {x}"));
            }
        }
    }
    Ok(())
}

/// The dbspec.read_file and dbspec.read_bytes ops: a file with errors gives the expect's diagnostics, each with the message of
/// its rule; a file without errors gives its bytes as text, which parse and emit unchanged.
fn dbspec_read(step: &Value, dir: &Path, want: &Value) -> Result<(), String> {
    let want_errors = want["errors"].as_array().cloned().unwrap_or_default();
    let path = step["path"].as_str().unwrap_or_default();
    let full = dir.join(path);
    let (name, read) = if step["op"] == "dbspec.read_file" {
        (full.display().to_string(), dbspec::read_file(&full))
    } else {
        let bytes = std::fs::read(&full).map_err(|error| format!("{path}: {error}"))?;
        (path.to_owned(), dbspec::read_bytes(path, bytes).map_err(dbspec::ReadError::Diagnostics))
    };
    if !want_errors.is_empty() {
        let errors = match read {
            Err(dbspec::ReadError::Diagnostics(errors)) => errors,
            Ok(_) => return Err("the reader returned text with diagnostics".to_owned()),
            Err(dbspec::ReadError::Io(error)) => return Err(format!("{name}: {error}")),
        };
        let got = diagnostic_values(&errors);
        if got != want_errors {
            return Err(format!("diagnostics = {got:?}, want {want_errors:?}"));
        }
        for error in &errors {
            let suffix = if error.rule == "signature" { " is not a dbspec document" } else { " is not valid UTF-8" };
            if error.message != format!("{name}{suffix}") {
                return Err(format!("message {:?}, want {name}{suffix}", error.message));
            }
        }
        return Ok(());
    }
    let text = match read {
        Ok(text) => text,
        Err(dbspec::ReadError::Diagnostics(errors)) => return Err(format!("unexpected diagnostics {errors:?}")),
        Err(dbspec::ReadError::Io(error)) => return Err(format!("{name}: {error}")),
    };
    let bytes = std::fs::read(&full).map_err(|error| format!("{path}: {error}"))?;
    if text.as_bytes() != bytes.as_slice() {
        return Err("the reader text differs from the file bytes".to_owned());
    }
    let emitted = emit_stable(&text, &BTreeMap::new())?;
    if emitted != text {
        return Err(format!("the file text emits as:\n{emitted}"));
    }
    Ok(())
}

