/// One markdown.send step (FCV-3, FCV-4): a transaction begin, or the typed query of a slot column. The step runs on a
/// connection to a listener that records the first message it receives, and its expect is compared with that message, or with
/// the code of the error that the call returned before it sent one.
fn markdown_send(step: &Value) -> Result<(), String> {
    // The process zone is the TZ environment variable of the process, restored when the step ends (even on a panic). The
    // Rust connection zone is fixed at UTC, so the bound value does not depend on it.
    let _zone = step["process_zone"].as_str().map(ProcessZone::set);
    let send = SendStep::parse(step)?;
    send_and_check(step, Call::Send(send), "markdown.send")
}

/// One model.assign step (FCV-4): the public setter of a column of a new row of the slots model, then the insert that the
/// listener records. The setter takes text, so the Rust cases exclude a nil value (DSL-29).
fn collection_key(step: &Value, database: &str) -> Result<(), String> {
    let mut keys: Vec<polyspec_orm::Key> = Vec::new();
    let mut groups: Vec<usize> = Vec::new();
    let mut types: Vec<&str> = Vec::new();
    let mut failure = None;
    for entry in step["keys"].as_array().ok_or("collection.key has no keys")? {
        let value = match entry["type"].as_str().unwrap_or_default() {
            "null" => Val::Null,
            "text" => Val::Str(entry["value"].as_str().ok_or("a text key holds no text")?.to_owned()),
            "bool" => Val::Bool(entry["value"].as_bool().ok_or("a bool key holds no bool")?),
            "int" => Val::I64(entry["value"].as_i64().ok_or("an int key holds no integer")?),
            "bytes" => {
                let text = entry["hex"].as_str().ok_or("a bytes key holds no hex")?;
                let digits = (0..text.len()).step_by(2).map(|index| u8::from_str_radix(&text[index..index + 2], 16));
                Val::Bytes(digits.collect::<Result<Vec<u8>, _>>().map_err(|error| error.to_string())?)
            }
            "datetime" => {
                let text = entry["value"].as_str().ok_or("a datetime key holds no text")?;
                Val::DateTime(polyspec_orm::chrono::DateTime::parse_from_rfc3339(text).map_err(|error| error.to_string())?.naive_utc())
            }
            other => return Err(format!("collection.key has no type {other}")),
        };
        let key = match polyspec_orm::Key::of(&value) {
            Ok(key) => key,
            Err(error) => {
                failure = Some(json!({ "error": error.code(), "message": error.to_string() }));
                break;
            }
        };
        groups.push(keys.iter().position(|other| other == &key).map_or(keys.len(), |index| groups[index]));
        types.push(match (&key, &value) {
            (polyspec_orm::Key::I(left), Val::I64(right)) if left == right => "int",
            (polyspec_orm::Key::S(left), Val::Str(right)) if left == right => "text",
            (polyspec_orm::Key::B(left), Val::Bool(right)) if left == right => "bool",
            (polyspec_orm::Key::X(left), Val::Bytes(right)) if left == right => "bytes",
            (polyspec_orm::Key::T(left), Val::DateTime(right)) if left == right => "datetime",
            _ => return Err(format!("key {key:?} changed its native value")),
        });
        keys.push(key);
    }
    let got = failure.unwrap_or_else(|| json!({ "groups": groups, "types": types }));
    let want = &step["expect"][database];
    if &got == want {
        Ok(())
    } else {
        Err(format!("got {got}, want {want}"))
    }
}

fn model_assign(step: &Value) -> Result<(), String> {
    let model = step["model"].as_str().unwrap_or_default();
    let column = step["column"].as_str().unwrap_or_default();
    if model != "slots" || column != "varchar_value" {
        return Err(format!("model.assign of {model}.{column} has no typed setter in the Rust cases"));
    }
    let (wrapper, body) = kind(&step["value"])?;
    if wrapper == "nil" {
        return Err("the typed setter takes no null, so the Rust cases exclude a nil value".to_owned());
    }
    let text = body.as_str().ok_or_else(|| format!("the value {} holds no text", step["value"]))?;
    send_and_check(step, Call::Assign(text.to_owned()), "model.assign")
}

/// Runs one call on a connection to a listener of its own, and checks the first message that the listener records, or the
/// code of the error that the call returned before it sent one, against the expect of `step`.
fn send_and_check(step: &Value, call: Call, op: &str) -> Result<(), String> {
    let listener = markdown::send_listener();
    let result = call_on_connection(listener.dsn.clone(), call);
    let sent = match (listener.finish(), result) {
        (Some(message), _) => Sent::Message(message_value(&message)?),
        (None, Err(error)) => Sent::Error(error.code().to_owned()),
        (None, Ok(())) => return Err("the call returned and sent no message".to_owned()),
    };
    let expect = &step["expect"];
    if let Some(want) = expect.get("error") {
        let want = want.as_str().unwrap_or_default();
        return match sent {
            Sent::Error(code) if code == want => Ok(()),
            Sent::Error(code) => Err(format!("the call returned error {code}, want {want}")),
            Sent::Message(message) => Err(format!("the call sent {message} and returned no error, want {want}")),
        };
    }
    let Some(want) = expect.get("message") else { return Err(format!("{op} expects a message or an error")) };
    match sent {
        Sent::Message(got) if same_message(&got, want) => Ok(()),
        Sent::Message(got) => Err(format!("message {got}, want {want}")),
        Sent::Error(code) => Err(format!("the call returned error {code} before a message")),
    }
}

/// A message equals its expect by value; two numbers compare by their value, so the float 5.0 of an f64 column equals 5.
fn same_message(got: &Value, want: &Value) -> bool {
    match (got, want) {
        // Two integers are compared exactly, so an i64 that is off by one fails; a float or a mix compares by value.
        (Value::Number(x), Value::Number(y)) => match (x.as_i64(), y.as_i64()) {
            (Some(a), Some(b)) => a == b,
            _ => match (x.as_f64(), y.as_f64()) {
                (Some(a), Some(b)) => a == b || a.is_nan() && b.is_nan(),
                _ => false,
            },
        },
        _ => got == want,
    }
}

/// The TZ environment variable as the process zone of one markdown.send step; the previous value is restored on drop.
struct ProcessZone {
    previous: Option<std::ffi::OsString>,
}

impl ProcessZone {
    fn set(zone: &str) -> Self {
        let previous = std::env::var_os("TZ");
        std::env::set_var("TZ", zone);
        Self { previous }
    }
}

impl Drop for ProcessZone {
    fn drop(&mut self) {
        match self.previous.take() {
            Some(value) => std::env::set_var("TZ", value),
            None => std::env::remove_var("TZ"),
        }
    }
}

/// What a markdown.send call sent: the value of its first message, or the code of its error.
enum Sent {
    Message(Value),
    Error(String),
}

/// What one listener step runs on its connection: a markdown.send call, or the text of a model.assign setter.
enum Call {
    Send(SendStep),
    Assign(String),
    /// The builder calls of a markdown.builder step, by name.
    Builder(Vec<String>),
}

/// The call of one markdown.send step: a transaction begin with its read_only option, or a statement with its column and the
/// text of its one parameter.
struct SendStep {
    begin: Option<bool>,
    column: String,
    value: Filter,
    /// The contains condition (the like_contains operator) of the column, which the generated lk method runs (DSL-29).
    contains: bool,
    /// The operator of the step, which selects the chain method of Eq, Ne or Gt (DSL-50).
    operator: String,
}

/// The typed filter value of a statement: the text of a string column, the integer that the text of an integer column
/// converts to the host type of its column, the float of a float column, or the bool of a bool column (a value that does not
/// convert is an error of the step, not a pass).
enum Filter {
    Text(String),
    Bytes(Vec<u8>),
    Nil,
    I16(i16),
    I32(i32),
    I64(i64),
    I64List(Vec<i64>),
    F64(f64),
    Bool(bool),
}

impl SendStep {
    fn parse(step: &Value) -> Result<Self, String> {
        if let Some(begin) = step.get("begin") {
            return Ok(Self {
                begin: Some(begin["read_only"].as_bool().unwrap_or(false)),
                column: String::new(),
                value: Filter::Text(String::new()),
                contains: false,
                operator: String::new(),
            });
        }
        let operator = step["operator"].as_str().unwrap_or_default();
        let contains = match operator {
            "eq" => false,
            "like_contains" => true,
            "eq_method" | "ne_method" | "gt_method" => false,
            _ => return Err(format!("operator {operator} has no typed filter in the Rust cases")),
        };
        let column = step["column"].as_str().unwrap_or_default();
        if contains && column != "slots.text_value" {
            return Err(format!("the column {column} has no contains filter in the Rust cases"));
        }
        if !SEND_COLUMNS.contains(&column) {
            return Err(format!("the column {column} has no typed filter in the Rust cases"));
        }
        // The typed filters take the wrapper of the parameter: the runtime reads it in the form of the column type (FCV-4).
        let (wrapper, body) = kind(&step["params"][0])?;
        let value = match column {
            _ if wrapper == "nil" => Filter::Nil,
            "slots.i64_value" if wrapper == "array" => {
                let items = body.as_array().ok_or_else(|| format!("the parameter {} holds no list", step["params"][0]))?;
                let list = items
                    .iter()
                    .map(|item| {
                        let text = item["int"].as_str().ok_or_else(|| format!("the list item {item} holds no int"))?;
                        integer::<i64>(column, text)
                    })
                    .collect::<Result<Vec<i64>, String>>()?;
                Filter::I64List(list)
            }
            "slots.f64_value" => Filter::F64(float(column, wrapper, body)?),
            "slots.bool_value" => Filter::Bool(boolean(column, wrapper, body)?),
            "slots.bytes_value" => {
                let hex = body.as_str().ok_or_else(|| format!("the parameter {} holds no hex", step["params"][0]))?;
                Filter::Bytes(hex_bytes(hex)?)
            }
            _ => {
                let text = body.as_str().ok_or_else(|| format!("the parameter {} holds no text", step["params"][0]))?;
                match column {
                    "slots.i16_value" => Filter::I16(integer(column, text)?),
                    "slots.i32_value" => Filter::I32(integer(column, text)?),
                    "slots.i64_value" => Filter::I64(integer(column, text)?),
                    _ => Filter::Text(text.to_owned()),
                }
            }
        };
        Ok(Self { begin: None, column: column.to_owned(), value, contains, operator: operator.to_owned() })
    }

    /// Runs the call on the connection `db`.
    async fn call(&self, db: &polyspec_orm::Db) -> polyspec_orm::Result<()> {
        if let Some(read_only) = self.begin {
            return if read_only { db.transaction(async || Ok(())).read_only().await } else { db.transaction(async || Ok(())).await };
        }
        if self.contains {
            return match &self.value {
                Filter::Text(v) => bind_model::Slots::new().connect(db).lk_text_value(v.as_str()).gets().await.map(drop),
                Filter::Nil => unreachable!("the typed contains method takes no null, so the Rust cases exclude a nil wrapper"),
                _ => unreachable!("the Rust cases exclude a contains wrapper of another kind"),
            };
        }
        match (self.operator.as_str(), &self.value) {
            ("eq_method", Filter::I64List(v)) => return bind_model::Slots::new().connect(db).eq_i64_value(v.clone()).gets().await.map(drop),
            ("ne_method", Filter::I64List(v)) => return bind_model::Slots::new().connect(db).ne_i64_value(v.clone()).gets().await.map(drop),
            ("gt_method", Filter::I64(v)) => return bind_model::Slots::new().connect(db).gt_i64_value(*v).gets().await.map(drop),
            _ => {}
        }
        match (self.column.as_str(), &self.value) {
            ("slots.i64_value", Filter::I64List(v)) => bind_model::Slots::new().connect(db).i64_value(v.clone()).gets().await.map(drop),
            ("slots.time0_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).time0_value(v.as_str()).gets().await.map(drop),
            ("slots.time3_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).time3_value(v.as_str()).gets().await.map(drop),
            ("slots.time6_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).time6_value(v.as_str()).gets().await.map(drop),
            ("slots.datetime0_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).datetime0_value(v.as_str()).gets().await.map(drop),
            ("slots.datetime3_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).datetime3_value(v.as_str()).gets().await.map(drop),
            ("slots.datetime6_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).datetime6_value(v.as_str()).gets().await.map(drop),
            ("slots.date_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).date_value(v.as_str()).gets().await.map(drop),
            ("slots.varchar_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).varchar_value(v.as_str()).gets().await.map(drop),
            ("slots.varchar_null_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).varchar_null_value(v.as_str()).gets().await.map(drop),
            ("slots.varchar_null_value", Filter::Nil) => bind_model::Slots::new().connect(db).varchar_null_value(polyspec_orm::Null).gets().await.map(drop),
            ("slots.varchar_long_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).varchar_long_value(v.as_str()).gets().await.map(drop),
            ("slots.text_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).text_value(v.as_str()).gets().await.map(drop),
            ("slots.uuid_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).uuid_value(v.as_str()).gets().await.map(drop),
            ("slots.time1_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).time1_value(v.as_str()).gets().await.map(drop),
            ("slots.time2_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).time2_value(v.as_str()).gets().await.map(drop),
            ("slots.datetime1_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).datetime1_value(v.as_str()).gets().await.map(drop),
            ("slots.datetime2_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).datetime2_value(v.as_str()).gets().await.map(drop),
            ("slots.bytes_value", Filter::Bytes(v)) => bind_model::Slots::new().connect(db).bytes_value(v.clone()).gets().await.map(drop),
            ("slots.decimal_value", Filter::Text(v)) => bind_model::Slots::new().connect(db).decimal_value(v.as_str()).gets().await.map(drop),
            ("slots.i16_value", Filter::I16(v)) => bind_model::Slots::new().connect(db).i16_value(*v).gets().await.map(drop),
            ("slots.i32_value", Filter::I32(v)) => bind_model::Slots::new().connect(db).i32_value(*v).gets().await.map(drop),
            ("slots.i64_value", Filter::I64(v)) => bind_model::Slots::new().connect(db).i64_value(*v).gets().await.map(drop),
            ("slots.f64_value", Filter::F64(v)) => bind_model::Slots::new().connect(db).f64_value(*v).gets().await.map(drop),
            ("slots.bool_value", Filter::Bool(v)) => bind_model::Slots::new().connect(db).bool_value(*v).gets().await.map(drop),
            (column, _) => unreachable!("parse builds the filter of each column of SEND_COLUMNS, not {column}"),
        }
    }
}

/// The integer of a statement's text for the host type `T` of its column; a text outside the range of `T` is an error.
fn integer<T: std::str::FromStr>(column: &str, text: &str) -> Result<T, String>
where
    T::Err: std::fmt::Display,
{
    text.parse::<T>().map_err(|error| format!("the parameter {text:?} of {column} is no integer of its host type: {error}"))
}

/// The float of a float column's parameter: a float or f64 wrapper, or an int wrapper, parsed as an f64. Rust parses NaN,
/// Infinity and -Infinity, the three non-finite values of the f64 wrapper; a text that does not parse is an error of the step.
fn float(column: &str, wrapper: &str, body: &Value) -> Result<f64, String> {
    match wrapper {
        "float" | "f64" | "int" => {
            let text = body.as_str().ok_or_else(|| format!("the parameter of {column} holds no text"))?;
            text.parse::<f64>().map_err(|error| format!("the parameter {text:?} of {column} is no float: {error}"))
        }
        other => Err(format!("a {other} wrapper is no float parameter of {column}")),
    }
}

/// The bool of a bool column's parameter: a bool wrapper holding a JSON boolean.
fn boolean(column: &str, wrapper: &str, body: &Value) -> Result<bool, String> {
    match (wrapper, body.as_bool()) {
        ("bool", Some(value)) => Ok(value),
        _ => Err(format!("the parameter of {column} is no bool wrapper holding a boolean")),
    }
}

/// Runs one call on a connection to `dsn` with a current-thread runtime, on a thread with a stack of its own (the futures of
/// the calls are large in a debug build), and closes the connection after the call.
fn call_on_connection(dsn: String, call: Call) -> polyspec_orm::Result<()> {
    match std::thread::Builder::new()
        .stack_size(64 << 20)
        .spawn(move || {
            let runtime = tokio::runtime::Builder::new_current_thread().enable_all().build().expect("a current-thread runtime");
            runtime.block_on(async {
                let db = bind_model::connect(&dsn, 1, polyspec_orm::Config::default()).await.expect("connect");
                let result = match &call {
                    Call::Send(send) => send.call(&db).await,
                    Call::Assign(text) => bind_model::Slots::new().connect(&db).set_varchar_value(text.as_str()).create().await.map(drop),
                    Call::Builder(calls) => {
                        let mut model = bind_model::Slots::new().connect(&db);
                        for call in calls {
                            model = match call.as_str() {
                                "limit_zero_count" => model.limit(0, 0),
                                "empty_i64_list" => model.i64_value(Vec::<i64>::new()),
                                "empty_varchar_list" => model.varchar_value(Vec::<String>::new()),
                                other => panic!("markdown.builder call {other} has no builder call in the Rust cases"),
                            };
                        }
                        model.get_count().await.map(drop)
                    }
                };
                db.close().await;
                result
            })
        })
        .expect("a thread with a 64 MiB stack")
        .join()
    {
        Ok(result) => result,
        Err(panic) => std::panic::resume_unwind(panic),
    }
}

/// The message value that an expect compares: the whole message of a begin, or the one parameter of a statement.
fn message_value(message: &Value) -> Result<Value, String> {
    if message["op"] == "begin" {
        return Ok(message.clone());
    }
    match message["params"].as_array().map(Vec::as_slice) {
        // A statement with no parameter (a nil compared with eq is IS NULL, DSL-48) has the empty list as its message.
        Some([]) => Ok(Value::Array(Vec::new())),
        Some([only]) => Ok(only.clone()),
        // A list of several parameters (a list condition, DSL-50) is compared as the list.
        Some(several) => Ok(Value::Array(several.to_vec())),
        None => Err(format!("the statement message {message} holds no parameters")),
    }
}

/// The cell form of a value a host decode read.
fn read_param(read: Val) -> Param {
    match read {
        Val::Str(text) => Param::Str(text),
        Val::Bytes(bytes) => Param::Bytes(bytes),
        other => Param::Str(format!("{other:?}")),
    }
}

/// Compares the cell of an encode, a host decode or a blind index with a wrapper: bytes by bytes, a text cell by its UTF-8
/// bytes (FCV-4), and SQL NULL with null.
fn compare_cell(want: &Value, cell: &Param) -> Result<(), String> {
    let got: Vec<u8> = match cell {
        Param::Null if want.get("null").is_some() => return Ok(()),
        Param::Null => return Err(format!("no cell, want {want}")),
        Param::Str(text) => text.as_bytes().to_vec(),
        Param::Bytes(bytes) => bytes.clone(),
        other => return Err(format!("cell {other:?}")),
    };
    let expected = if let Some(hex) = want["bytes_hex"].as_str() {
        hex_bytes(hex)?
    } else if let Some(text) = want["text"].as_str() {
        text.as_bytes().to_vec()
    } else {
        return Err(format!("a cell compares with bytes_hex or text, not {want}"));
    };
    if got == expected {
        Ok(())
    } else {
        Err(format!("cell {}, want {}", hex_text(&got), hex_text(&expected)))
    }
}

fn hex_bytes(hex: &str) -> Result<Vec<u8>, String> {
    (0..hex.len()).step_by(2).map(|i| u8::from_str_radix(hex.get(i..i + 2).unwrap_or("x"), 16).map_err(|e| e.to_string())).collect()
}

fn hex_text(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn reference<'a>(name: &str, bound: &'a HashMap<String, Outcome>) -> Result<&'a Produced, String> {
    match bound.get(name) {
        None => Err(format!("ref {name} names no bound result")),
        Some(Err((_, message))) => Err(format!("ref {name} names a failed step: {message}")),
        Some(Ok(produced)) => Ok(produced),
    }
}

/// A stored cell: the cell a ref names, or a wrapper's text, bytes or SQL NULL.
fn cell(raw: &Value, bound: &HashMap<String, Outcome>) -> Result<Val, String> {
    if let Some(name) = raw["ref"].as_str() {
        return Ok(match reference(name, bound)? {
            Produced::Written(Param::Null) => Val::Null,
            Produced::Written(Param::Str(text)) => Val::Str(text.clone()),
            Produced::Written(Param::Bytes(bytes)) => Val::Bytes(bytes.clone()),
            Produced::Read(read) => read.clone(),
            Produced::Written(other) => return Err(format!("ref {name} is the cell {other:?}")),
            Produced::Document(_) | Produced::Plan(_) | Produced::Plain(_) => return Err(format!("ref {name} is a dbspec value")),
        });
    }
    match kind(raw)? {
        ("null", _) => Ok(Val::Null),
        ("text", body) => Ok(Val::Str(body.as_str().unwrap_or_default().to_owned())),
        ("bytes_hex", body) => Ok(Val::Bytes(hex_bytes(body.as_str().unwrap_or_default())?)),
        (other, _) => Err(format!("a {other} wrapper is not a cell")),
    }
}

/// A bound value of a host encode or a blind index: text, bytes, an integer, a float, a bool or SQL NULL.
fn param(raw: &Value, bound: &HashMap<String, Outcome>) -> Result<Param, String> {
    if let Some(name) = raw["ref"].as_str() {
        return match reference(name, bound)? {
            Produced::Written(written) => Ok(written.clone()),
            Produced::Read(read) => Ok(read_param(read.clone())),
            Produced::Document(_) | Produced::Plan(_) | Produced::Plain(_) => Err(format!("ref {name} is a dbspec value")),
        };
    }
    match kind(raw)? {
        ("null", _) => Ok(Param::Null),
        ("text", body) => Ok(Param::Str(body.as_str().unwrap_or_default().to_owned())),
        ("bytes_hex", body) => Ok(Param::Bytes(hex_bytes(body.as_str().unwrap_or_default())?)),
        ("int", body) => body.as_str().unwrap_or_default().parse().map(Param::I64).map_err(|error| format!("int wrapper: {error}")),
        ("float", body) => body.as_str().unwrap_or_default().parse().map(Param::F64).map_err(|error| format!("float wrapper: {error}")),
        // Rust parses NaN, Infinity and -Infinity, the three non-finite values of the f64 wrapper.
        ("f64", body) => body.as_str().unwrap_or_default().parse().map(Param::F64).map_err(|error| format!("f64 wrapper: {error}")),
        ("bool", body) => body.as_bool().map(Param::Bool).ok_or_else(|| "a bool wrapper holds no boolean".to_owned()),
        (other, _) => Err(format!("a {other} wrapper is not a bound value")),
    }
}

/// An encode: SQL NULL for null, an ordered-json value for an ordered_json stage, so that its member order and number
/// text are those of the recipe, and the common value model otherwise.
fn encode(styles: &[String], raw: &Value, bound: &HashMap<String, Outcome>) -> Result<polyspec_orm::Result<Param>, String> {
    let stages: Vec<&str> = styles.iter().map(String::as_str).collect();
    if let Some(name) = raw["ref"].as_str() {
        return Ok(match reference(name, bound)? {
            Produced::Read(Val::Null) => Ok(Param::Null),
            Produced::Read(Val::Ordered(value)) => codec::encode_ordered(&stages, StyledValue::Value(value)),
            Produced::Read(Val::Json(value)) => codec::encode(&stages, StyledValue::Value(value)),
            Produced::Read(Val::Str(text)) => codec::encode(&stages, StyledValue::Value(&Value::String(text.clone()))),
            _ => return Err(format!("ref {name} is not a decoded value")),
        });
    }
    if raw.get("null").is_some() {
        return Ok(codec::encode(&stages, StyledValue::SqlNull));
    }
    // An ordered_json wrapper is the ordered-json value of its value, whatever the stages (FCV-4).
    if let Some(inner) = raw.get("ordered_json") {
        let value = ordered_json::parse(&json_text(inner)?).map_err(|e| e.to_string())?;
        return Ok(codec::encode_ordered(&stages, StyledValue::Value(&value)));
    }
    if styles.iter().any(|s| s == "ordered_json") {
        let value = ordered_json::parse(&json_text(raw)?).map_err(|e| e.to_string())?;
        return Ok(codec::encode_ordered(&stages, StyledValue::Value(&value)));
    }
    Ok(codec::encode(&stages, StyledValue::Value(&to_value(raw)?)))
}

fn kind(w: &Value) -> Result<(&str, &Value), String> {
    match w.as_object() {
        Some(map) if map.len() == 1 => map.iter().next().map(|(k, v)| (k.as_str(), v)).ok_or_else(|| format!("{w}")),
        _ => Err(format!("a value is a wrapper with one key: {w}")),
    }
}

/// A wrapper as JSON text with its members in order and its numbers as their recipe text.
fn json_text(w: &Value) -> Result<String, String> {
    Ok(match kind(w)? {
        ("nil", _) => "null".to_owned(),
        ("bool", body) => body.to_string(),
        ("int" | "float", body) => body.as_str().unwrap_or_default().to_owned(),
        ("text", body) => body.to_string(),
        ("array", body) => {
            let items: Result<Vec<String>, String> = body.as_array().into_iter().flatten().map(json_text).collect();
            format!("[{}]", items?.join(","))
        }
        ("object", body) => {
            let mut parts = Vec::new();
            for pair in body.as_array().into_iter().flatten() {
                parts.push(format!("{}:{}", pair[0], json_text(&pair[1])?));
            }
            format!("{{{}}}", parts.join(","))
        }
        (other, _) => return Err(format!("a {other} wrapper is not a codec value")),
    })
}

/// The serde_json value of a wrapper in the common value model of COD-16.
fn to_value(w: &Value) -> Result<Value, String> {
    Ok(match kind(w)? {
        ("nil", _) => Value::Null,
        ("bool", body) => body.clone(),
        ("int", body) => {
            let text = body.as_str().unwrap_or_default();
            match text.parse::<i64>() {
                Ok(i) => Value::from(i),
                Err(_) => Value::from(text.parse::<u64>().map_err(|e| e.to_string())?),
            }
        }
        ("float", body) => {
            let f: f64 = body.as_str().unwrap_or_default().parse().map_err(|e: std::num::ParseFloatError| e.to_string())?;
            Value::Number(Number::from_f64(f).ok_or("a float is finite")?)
        }
        ("text", body) => body.clone(),
        ("array", body) => Value::Array(body.as_array().into_iter().flatten().map(to_value).collect::<Result<_, _>>()?),
        ("object", body) => {
            let mut map = Map::new();
            for pair in body.as_array().into_iter().flatten() {
                map.insert(pair[0].as_str().unwrap_or_default().to_owned(), to_value(&pair[1])?);
            }
            Value::Object(map)
        }
        (other, _) => return Err(format!("a {other} wrapper is not a codec value")),
    })
}

/// The wrapper of a decoded value; an ordered-json value keeps its member order and number text.
fn from_val(read: &Val) -> Result<Value, String> {
    Ok(match read {
        Val::Ordered(value) => from_ordered(value)?,
        Val::Json(value) => from_json(value),
        Val::Str(text) => serde_json::json!({ "text": text }),
        Val::Bytes(bytes) => serde_json::json!({ "bytes_hex": hex_text(bytes) }),
        Val::I64(i) => serde_json::json!({ "int": i.to_string() }),
        Val::F64(f) => serde_json::json!({ "float": f.to_string() }),
        Val::Bool(b) => serde_json::json!({ "bool": b }),
        other => return Err(format!("decoded {other:?}")),
    })
}

fn from_json(value: &Value) -> Value {
    match value {
        Value::Null => serde_json::json!({ "nil": true }),
        Value::Bool(b) => serde_json::json!({ "bool": b }),
        Value::Number(n) if n.is_f64() => serde_json::json!({ "float": n.to_string() }),
        Value::Number(n) => serde_json::json!({ "int": n.to_string() }),
        Value::String(s) => serde_json::json!({ "text": s }),
        Value::Array(items) => serde_json::json!({ "array": items.iter().map(from_json).collect::<Vec<_>>() }),
        Value::Object(map) => serde_json::json!({ "object": map.iter().map(|(k, v)| serde_json::json!([k, from_json(v)])).collect::<Vec<_>>() }),
    }
}

fn from_ordered(value: &ordered_json::Value) -> Result<Value, String> {
    Ok(match value.kind() {
        Kind::Null => serde_json::json!({ "nil": true }),
        Kind::Boolean => serde_json::json!({ "bool": value.boolean_value() }),
        Kind::String => serde_json::json!({ "text": String::from_utf8(value.string_value().map_err(|e| e.to_string())?).map_err(|e| e.to_string())? }),
        Kind::Number => {
            let text = value.number_literal().unwrap_or_default();
            if text.contains(['.', 'e', 'E']) {
                serde_json::json!({ "float": text })
            } else {
                serde_json::json!({ "int": text })
            }
        }
        Kind::Array => serde_json::json!({ "array": value.items().unwrap_or_default().iter().map(from_ordered).collect::<Result<Vec<_>, _>>()? }),
        Kind::Object => {
            let mut pairs = Vec::new();
            for (k, v) in value.members().into_iter().flat_map(|m| m.iter()) {
                let name = String::from_utf8(k.string_value().map_err(|e| e.to_string())?).map_err(|e| e.to_string())?;
                pairs.push(serde_json::json!([name, from_ordered(v)?]));
            }
            serde_json::json!({ "object": pairs })
        }
    })
}

/// The number of a wrapper text; a text that is not a number is a fault of the recipe or the helper, which the schema refuses.
fn number<T: std::str::FromStr>(v: &Value) -> T
where
    T::Err: std::fmt::Display,
{
    match v.as_str().map(str::parse::<T>) {
        Some(Ok(n)) => n,
        Some(Err(error)) => panic!("the number text {v} does not parse: {error}"),
        None => panic!("the number {v} is not a text"),
    }
}

/// Compares a decoded wrapper with an expected one: an ordered-json value by its number text and member order (COD-16),
/// every other value by number value and with its object as a set of pairs (FCV-4).
fn equal(got: &Value, want: &Value, ordered: bool) -> bool {
    let (Ok((kind, a)), Ok((wanted, b))) = (self::kind(got), self::kind(want)) else { return false };
    if kind != wanted {
        return false;
    }
    match kind {
        "float" if !ordered => {
            let (x, y) = (number::<f64>(a), number::<f64>(b));
            x == y || x.is_nan() && y.is_nan()
        }
        "int" if !ordered => number::<i128>(a) == number::<i128>(b),
        "array" => {
            let (x, y) = (a.as_array().cloned().unwrap_or_default(), b.as_array().cloned().unwrap_or_default());
            x.len() == y.len() && x.iter().zip(&y).all(|(g, w)| equal(g, w, ordered))
        }
        "object" => {
            let (x, y) = (a.as_array().cloned().unwrap_or_default(), b.as_array().cloned().unwrap_or_default());
            if x.len() != y.len() {
                return false;
            }
            if ordered {
                x.iter().zip(&y).all(|(g, w)| g[0] == w[0] && equal(&g[1], &w[1], ordered))
            } else {
                y.iter().all(|w| x.iter().any(|g| g[0] == w[0] && equal(&g[1], &w[1], ordered)))
            }
        }
        _ => a == b,
    }
}

