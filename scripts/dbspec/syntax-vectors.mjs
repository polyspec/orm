// syntax-vectors.mjs writes tests/dbspec/syntax.json: the expected tokens of the main document of every canonical,
// normalize, invalid, sets and hashes case of tests/dbspec/cases.json, from the TypeScript analyzeDbspec.
//
// Usage (after the TypeScript build): node scripts/dbspec/syntax-vectors.mjs
// Running it twice gives the same bytes. A case it cannot read is an error that stops the run; no case is skipped.
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { readCases } from '../../tests/dbspec/cases.mjs';

const root = new URL('../../', import.meta.url);
const outPath = new URL('tests/dbspec/syntax.json', root);
const distPath = new URL('packages/orm-npm/dist/dbspec/index.js', root);

const SECTIONS = ['canonical', 'normalize', 'invalid'];
const NOTE =
  'Expected tokens of the main document of each canonical, normalize, invalid, sets and hashes case of cases.json, ' +
  'generated by scripts/dbspec/syntax-vectors.mjs from the TypeScript analyzeDbspec. A token is [line, start, end, class]: ' +
  'line is 1-based, start and end count code points on the line. A sets case id ends with the 1-based place of its document ' +
  'in documents; a hashes case id ends with the document name. Every runtime must match these tokens exactly.';

// join writes lines with LF, with CRLF when crlf is true, or with alternating CRLF and LF and no final line end when mixed is true.
export function join(lines, crlf, mixed = false) {
  if (mixed) return lines.map((line, i) => (i === lines.length - 1 ? line : line + (i % 2 === 0 ? '\r\n' : '\n'))).join('');
  const end = crlf ? '\r\n' : '\n';
  return lines.join(end) + end;
}

const headerName = lines => lines[0].split(' ')[2];

// vectorInputs lists, in file order, the text and the other documents of every analysis the vectors need.
export function vectorInputs(cases) {
  const inputs = [];
  for (const section of SECTIONS) {
    for (const c of cases[section]) {
      const main = c.documents[c.main];
      if (main === undefined) throw new Error(`${section}/${c.id}: the main document ${c.main} is missing`);
      const documents = {};
      for (const [name, lines] of Object.entries(c.documents)) {
        if (name !== c.main) documents[name] = join(lines, c.crlf === true, c.mixed === true);
      }
      inputs.push({ id: `${section}/${c.id}`, text: join(main, c.crlf === true, c.mixed === true), documents });
    }
  }
  for (const c of cases.sets) {
    const all = [...c.documents, ...(c.external ?? [])];
    c.documents.forEach((lines, i) => {
      const documents = {};
      for (const [name, other] of Object.entries(c.parsing)) documents[name] = join(other, false);
      all.forEach((other, j) => {
        if (j !== i) documents[headerName(other)] = join(other, false);
      });
      inputs.push({ id: `sets/${c.id}/${i + 1}`, text: join(lines, false), documents });
    });
  }
  for (const c of cases.hashes) {
    for (const name of Object.keys(c.documents)) {
      const documents = {};
      for (const [other, lines] of Object.entries(c.documents)) {
        if (other !== name) documents[other] = join(lines, false);
      }
      inputs.push({ id: `hashes/${c.id}/${name}`, text: join(c.documents[name], false), documents });
    }
  }
  return inputs;
}

// generate analyzes every input and gives its id with its tokens as [line, start, end, class] arrays.
export function generate(analyze, inputs) {
  return inputs.map(({ id, text, documents }) => {
    let result;
    try {
      result = analyze(text, documents);
    } catch (error) {
      throw new Error(`${id}: analyzeDbspec failed: ${error.message}`);
    }
    return { id, tokens: result.tokens.map(t => [t.line, t.start, t.end, t.class]) };
  });
}

// render writes the file: the header, then one case per line.
export function render(entries) {
  const lines = entries.map(entry => JSON.stringify(entry));
  return `{"version": 1, "note": ${JSON.stringify(NOTE)}, "cases": [\n${lines.join(',\n')}\n]}\n`;
}

async function main() {
  const cases = readCases();
  const { analyzeDbspec } = await import(distPath.href);
  writeFileSync(outPath, render(generate(analyzeDbspec, vectorInputs(cases))));
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
