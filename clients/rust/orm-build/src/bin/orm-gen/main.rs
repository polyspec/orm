//! orm-gen: schema tooling for the Rust ORM.
//!
//! ```text
//! orm-gen build <schema/*.mmd...> --out schema/schema.json
//! orm-gen ddl --schema <source> --dialect mysql|postgres|sqlite --out <file.sql>
//! orm-gen diff --from <source> --to <source> --dialect mysql|postgres|sqlite --out <file.sql> [--allow-destructive]
//! orm-gen import --dsn <dsn> --out schema/app.mmd [--tables a,b]
//! orm-gen validate --dsn <dsn> --schema schema/schema.json
//! orm-gen migrate --dsn <dsn> --schema <source> [--migration-id id] [--dry-run]
//! orm-gen plan --from <source> --to <source> --dialect mysql|postgres|sqlite --out YYYYMMDD-name.json
//! orm-gen apply --plan YYYYMMDD-name.json --dsn <dsn> --schema schema.json [--allow-destructive]
//! orm-gen recover (--plan YYYYMMDD-name.json | --migration-id id) --dsn <dsn> --schema schema.json
//! orm-gen rollback --plan YYYYMMDD-name.json --dsn <dsn> [--allow-destructive]
//! orm-gen verify --dsn <dsn> --schema schema.json
//! ```
//!
//! A source is a Mermaid file, a schema.json, SQL generated by these tools,
//! or `db:<dsn>`. A DSN is a `mysql://`, `postgres://`, or `sqlite://` URI.

mod args;
mod db;
mod introspect;
mod migrate;

use std::collections::HashSet;
use std::process::exit;

use orm_build::{ddl, live, schema};

use crate::args::Args;

const USAGE: &str = "usage: orm-gen build <files.mmd...> --out schema/schema.json
       orm-gen import --dsn <dsn> --out schema/app.mmd [--tables a,b]
       orm-gen validate --dsn <dsn> --schema schema/schema.json
       orm-gen ddl --schema <source> --dialect mysql|postgres|sqlite --out <file.sql>
       orm-gen diff --from <source> --to <source> --dialect mysql|postgres|sqlite --out <file.sql> [--allow-destructive]
       orm-gen migrate --dsn <dsn> --schema <source> [--migration-id id] [--dry-run]
       orm-gen plan --from <source> --to <source> --dialect mysql|postgres|sqlite --out migration.json
       source: schema.mmd | schema.json | orm-gen.sql | db:<dsn>
       dsn: mysql://… | postgres://… | sqlite:///path
       orm-gen apply --plan migration.json --dsn <dsn> --schema schema.json [--allow-destructive]
       orm-gen recover (--plan migration.json | --migration-id id) --dsn <dsn> --schema schema.json
       orm-gen rollback --plan YYYYMMDD-name.json --dsn <dsn> [--allow-destructive]
       orm-gen verify --dsn <dsn> --schema schema/schema.json";

fn usage() -> ! {
    eprintln!("{USAGE}");
    exit(2);
}

fn fail(msg: impl std::fmt::Display) -> ! {
    eprintln!("orm-gen: {msg}");
    exit(1);
}

fn parse(argv: &[String], valued: &[&str], booleans: &[&str]) -> Args {
    Args::parse(argv, valued, booleans).unwrap_or_else(|e| {
        eprintln!("{e}");
        usage()
    })
}

#[tokio::main]
async fn main() {
    let argv: Vec<String> = std::env::args().skip(1).collect();
    let Some((command, rest)) = argv.split_first() else { usage() };
    let result = match command.as_str() {
        "build" => build(rest),
        "ddl" => ddl_command(rest).await,
        "diff" => diff_command(rest).await,
        "import" => import_command(rest).await,
        "validate" => validate_command(rest).await,
        "migrate" => migrate::migrate(&parse(rest, &["dsn", "schema", "migration-id", "name", "log-dir"], &["dry-run"])).await,
        "plan" => migrate::plan(&parse(rest, &["from", "to", "dialect", "out", "migration-id", "name"], &[])).await,
        "apply" => migrate::apply(&parse(rest, &["plan", "dsn", "schema", "log-dir"], &["allow-destructive"])).await,
        "verify" => migrate::verify(&parse(rest, &["dsn", "schema"], &[])).await,
        "recover" => migrate::recover(&parse(rest, &["plan", "migration-id", "dsn", "schema", "log-dir"], &[])).await,
        "rollback" => migrate::rollback(&parse(rest, &["plan", "dsn", "log-dir"], &["allow-destructive"])).await,
        _ => usage(),
    };
    if let Err(e) = result {
        fail(e);
    }
}

fn build(argv: &[String]) -> Result<(), String> {
    let a = parse(argv, &["out"], &[]);
    let out = a.value("out");
    if out.is_empty() || a.positional.is_empty() {
        usage();
    }
    let mut files = Vec::new();
    for pattern in &a.positional {
        let matches = args::glob(pattern);
        if matches.is_empty() {
            return Err(format!("no such file: {pattern}"));
        }
        files.extend(matches);
    }
    files.sort();
    let mut diagrams = Vec::new();
    for f in &files {
        let src = std::fs::read_to_string(f).map_err(|e| e.to_string())?;
        match schema::parse(&src) {
            Ok(d) => diagrams.push(d),
            Err(e) => {
                eprintln!("{f}:{e}");
                exit(1);
            }
        }
    }
    let m = schema::build(&diagrams).map_err(|e| e.to_string())?;
    for w in m.warnings() {
        eprintln!("warning: {w}");
    }
    std::fs::write(&out, m.marshal_indent() + "\n").map_err(|e| e.to_string())?;
    println!("orm-gen: {} entities → {out} (schema_hash {})", m.order.len(), m.schema_hash);
    Ok(())
}

async fn ddl_command(argv: &[String]) -> Result<(), String> {
    let a = parse(argv, &["schema", "dialect", "out"], &[]);
    let (schema_path, out) = (a.value("schema"), a.value("out"));
    let dialect = a.value_or("dialect", "mysql");
    if schema_path.is_empty() || out.is_empty() {
        eprintln!("usage: orm-gen ddl --schema schema/schema.json --dialect mysql|postgres|sqlite --out <file.sql>");
        exit(2);
    }
    let m = migrate::load_schema_source(&schema_path, &dialect).await?;
    let text = ddl::render_ddl(&m, &dialect)?;
    std::fs::write(&out, text).map_err(|e| e.to_string())?;
    eprintln!("orm-gen: {} tables ({dialect}) → {out}", m.order.len());
    Ok(())
}

async fn diff_command(argv: &[String]) -> Result<(), String> {
    let a = parse(argv, &["from", "to", "dialect", "out"], &["allow-destructive"]);
    let (from_path, to_path, out) = (a.value("from"), a.value("to"), a.value("out"));
    let dialect = a.value_or("dialect", "mysql");
    if from_path.is_empty() || to_path.is_empty() || out.is_empty() {
        eprintln!("usage: orm-gen diff --from old.json --to new.json --dialect mysql|postgres|sqlite --out <file.sql> [--allow-destructive]");
        exit(2);
    }
    let mut from = migrate::load_schema_source(&from_path, &dialect).await?;
    let mut to = migrate::load_schema_source(&to_path, &dialect).await?;
    migrate::align_source_checks(&from_path, &to_path, &mut from, &mut to).await?;
    let text = ddl::render_diff(&from, &to, &dialect, a.flag("allow-destructive"))?;
    std::fs::write(&out, text).map_err(|e| e.to_string())
}

async fn import_command(argv: &[String]) -> Result<(), String> {
    let a = parse(argv, &["dsn", "out", "tables"], &[]);
    let (dsn, out) = (a.value("dsn"), a.value("out"));
    if dsn.is_empty() || out.is_empty() {
        eprintln!("usage: orm-gen import --dsn <dsn> --out schema/app.mmd [--tables a,b]");
        exit(2);
    }
    let tables = a.value("tables");
    let only: Option<HashSet<String>> = (!tables.is_empty()).then(|| tables.split(',').map(|t| t.trim().to_owned()).collect());
    let (_database, mut conn, dsn) = db::open(&dsn).await?;
    let ts = introspect::read_tables(&mut conn, &dsn.dialect, only.as_ref()).await?;
    let prev = match std::fs::read_to_string(&out) {
        Ok(src) => Some(schema::parse(&src).map_err(|e| format!("{out}: {e} (fix or remove it before importing over it)"))?),
        Err(_) => None,
    };
    let bodies = introspect::trigger_bodies(&mut conn, &dsn.dialect).await?;
    let text = live::with_trigger_directives(&ts, &bodies, live::render_mermaid(&ts, prev.as_ref()));
    std::fs::write(&out, &text).map_err(|e| e.to_string())?;
    schema::parse(&text).map_err(|e| format!("imported diagram does not parse: {e}"))?;
    eprintln!("orm-gen: {} tables → {out}", ts.len());
    Ok(())
}

async fn validate_command(argv: &[String]) -> Result<(), String> {
    let a = parse(argv, &["dsn", "schema"], &[]);
    let (dsn, schema_path) = (a.value("dsn"), a.value("schema"));
    if dsn.is_empty() || schema_path.is_empty() {
        eprintln!("usage: orm-gen validate --dsn <dsn> --schema schema/schema.json");
        exit(2);
    }
    let (_database, mut conn, dsn) = db::open(&dsn).await?;
    let m = migrate::load_schema_source(&schema_path, &dsn.dialect).await?;
    let tables = live::without_managed(&introspect::read_tables(&mut conn, &dsn.dialect, None).await?);
    let diagram = schema::parse(&live::render_mermaid(&tables, None)).map_err(|e| format!("live schema does not parse: {e}"))?;
    let lm = schema::build(&[diagram]).map_err(|e| format!("live schema does not build: {e}"))?;
    let diffs = diff_manifests(&m, &lm, &dsn.dialect);
    for d in &diffs {
        println!("{d}");
    }
    if !diffs.is_empty() {
        eprintln!("orm-gen: {} differences between {schema_path} and the live database", diffs.len());
        exit(1);
    }
    eprintln!("orm-gen: {schema_path} matches the live database ({} entities)", m.order.len());
    Ok(())
}

/// Go's %v of a string slice.
fn list(v: &[String]) -> String {
    format!("[{}]", v.join(" "))
}

/// What the clients would get wrong against the live schema.
fn diff_manifests(want: &schema::Manifest, live: &schema::Manifest, dialect: &str) -> Vec<String> {
    let mut out = Vec::new();
    for we in want.ordered() {
        let Some(le) = live.entities.get(&we.name) else {
            out.push(format!("{}: table missing in the database", we.table));
            continue;
        };
        for wc in &we.columns {
            let Some(lc) = le.column(&wc.name) else {
                out.push(format!("{}.{}: column missing in the database", we.table, wc.name));
                continue;
            };
            if ddl::column_storage(wc, dialect).0 != ddl::column_storage(lc, dialect).0 {
                out.push(format!("{}.{}: type {} in manifest, {} in the database", we.table, wc.name, wc.typ, lc.typ));
            }
            if wc.nullable != lc.nullable {
                out.push(format!("{}.{}: nullable {} in manifest, {} in the database", we.table, wc.name, wc.nullable, lc.nullable));
            }
            if wc.auto != lc.auto {
                out.push(format!("{}.{}: auto_increment {} in manifest, {} in the database", we.table, wc.name, wc.auto, lc.auto));
            }
            if wc.styles != lc.styles {
                out.push(format!("{}.{}: styles {} in manifest, {} in the database", we.table, wc.name, list(&wc.styles), list(&lc.styles)));
            }
        }
        for lc in &le.columns {
            if we.column(&lc.name).is_none() {
                out.push(format!("{}.{}: column exists in the database but not in the manifest", we.table, lc.name));
            }
        }
        if we.pk != le.pk {
            out.push(format!("{}: primary key {} in manifest, {} in the database", we.table, list(&we.pk), list(&le.pk)));
        }
    }
    out
}
